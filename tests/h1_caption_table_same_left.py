"""h1 ТАБЛИЦЫ #3 — ПОДПИСЬ И ПЕРВАЯ ЯЧЕЙКА ТЕЛА С ОДНОГО X.

Отличие от #1: здесь сравниваем НАЧАЛО подписи (слово «Таблица») и
НАЧАЛО первой (верхне-левой) ячейки тела как единый левый край колонки —
у грамотно свёрстанной таблицы они должны стоять на одной вертикали.

Измеримый инвариант: x0(«Таблица») и x0(первая ячейка верхней строки тела)
различаются менее чем на 5pt. С учётом inset=10pt в ячейке текст обычно
правее границы; поэтому дополнительно проверяем, что граница тела
(x0_ячейки − inset) совпадает с подписью. Берём оба критерия — если хоть
один в пределах допуска, левый край согласован.

ОЖИДАЕМЫЙ БАГ: тело центрировано, первая ячейка «Альфа» уезжает к центру.
"""
import helpers as h

c = h.Checks("h1_caption_table_same_left")
pdf = h.compile("h1_caption_table_same_left.typ")
ws = [w for w in h.words(pdf) if w[0] == 1]

cap = [w for w in ws if w[5] == "Таблица"]
c.check("caption_present", len(cap) == 1, f"нет «Таблица»: {[w[5] for w in ws]}")

# Первая строка тела — слова «Альфа Бета Гамма»; верхне-левая ячейка «Альфа».
alpha = [w for w in ws if w[5] == "Альфа"]
c.check("first_cell_present", len(alpha) == 1,
        f"первая ячейка «Альфа» не найдена: {[w[5] for w in ws]}")

if cap and alpha:
    cap_x0 = cap[0][1]
    cell_x0 = alpha[0][1]
    INSET = 10.0  # config.figure.inset
    # Критерий A: тексты с одного x (если в ячейке нет горизонт. инсета слева).
    same_text = abs(cell_x0 - cap_x0) <= 5
    # Критерий B: граница тела (текст − inset) под подписью.
    border = cell_x0 - INSET
    same_border = abs(border - cap_x0) <= 5
    c.check(
        "caption_and_first_cell_same_left",
        same_text or same_border,
        f"левый край подписи и первой ячейки расходятся: подпись x0={cap_x0:.2f}, "
        f"ячейка «Альфа» x0={cell_x0:.2f} (Δтекст={cell_x0 - cap_x0:+.2f}), "
        f"граница тела (x0−inset)={border:.2f} (Δграница={border - cap_x0:+.2f}); "
        f"оба вне ±5pt. Тело таблицы центрировано. "
        f"Файл: gost732-2017/styles/figure.typ.",
    )
    # Дополнительно: первая ячейка стоит левее середины полосы.
    c.check(
        "first_cell_in_left_half",
        cell_x0 < 318,
        f"первая ячейка «Альфа» x0={cell_x0:.2f} — в правой половине полосы "
        f"(>318), тело явно центрировано/смещено вправо.",
    )

c.done()
