"""h1 ТАБЛИЦЫ #2 — УЗКАЯ ТАБЛИЦА НЕ ПО ЦЕНТРУ СТРАНИЦЫ.

Полоса набора: левое поле x≈85, правый край≈552.76, середина ≈ 318.
Одноколоночная таблица с одной короткой ячейкой [X] по ГОСТ обязана
стоять у ЛЕВОГО поля, а не по центру страницы.

Измеримый инвариант: единственная ячейка [X] имеет x0 < 200 (ближе к
полю 85, чем к центру), и её центр заметно левее центра полосы (318).

ОЖИДАЕМЫЙ БАГ: тело центрируется (X оказывается у середины, x0≈314).
"""
import helpers as h

c = h.Checks("h1_table_not_centered")
pdf = h.compile("h1_table_not_centered.typ")
ws = [w for w in h.words(pdf) if w[0] == 1]

cells = [w for w in ws if w[5] == "X"]
c.check("cell_present", len(cells) == 1,
        f"ячейка [X] не найдена ровно один раз: {[w[5] for w in ws]}")

LEFT, RIGHT = 85.04, 552.76
MID = (LEFT + RIGHT) / 2  # ≈ 318.9

if cells:
    x0, x1 = cells[0][1], cells[0][3]
    cx = (x0 + x1) / 2
    # 1) левый край ячейки ближе к полю, чем к центру.
    c.check(
        "cell_left_near_margin",
        x0 < 200,
        f"левый край узкой таблицы x0={x0:.2f} — не у поля (ожидали <200; "
        f"поле={LEFT}, центр полосы≈{MID:.0f}). Таблица отцентрирована. "
        f"Файл: gost732-2017/styles/figure.typ (нет align(left) для it.body).",
    )
    # 2) центр ячейки не совпадает с центром полосы (НЕ центрирована).
    c.check(
        "cell_not_page_centered",
        abs(cx - MID) > 80,
        f"центр ячейки cx={cx:.2f} совпал с центром полосы {MID:.1f} "
        f"(|Δ|={abs(cx - MID):.1f} < 80) — таблица по центру страницы.",
    )
    # 3) с учётом inset (10pt) текст должен быть около 85+10≈95, а не у центра.
    c.check(
        "cell_left_within_one_inset_of_margin",
        x0 < LEFT + 30,
        f"левый край x0={x0:.2f} далеко от поля+инсет (~95): отрыв "
        f"{x0 - LEFT:.1f}pt от поля {LEFT}.",
    )

c.done()
