"""h2 ТАБЛИЦЫ #3: многострочная подпись не наезжает на первую строку тела.

Подпись «Таблица 1 – ...» переносится на 3+ строки. Последняя строка подписи
не должна перекрывать (по вертикали) первую строку тела таблицы — между ними
обязан быть положительный зазор.

ИНВАРИАНТ:
  1) подпись реально занимает >= 3 текстовых строки (иначе тест не проверяет
     многострочность);
  2) yMax последней строки подписи < yMin первой строки тела (МЦЕЛЛ1/МЦЕЛЛ2),
     т.е. зазор > 0 — нет наезда.
"""
import helpers as h

c = h.Checks("h2_caption_multiline_no_overlap")
pdf = h.compile("h2_caption_multiline_no_overlap.typ")
ws = h.words(pdf)

# yMin первой строки тела
y_body_top = min(h.y_of(pdf, "МЦЕЛЛ1") or 1e9, h.y_of(pdf, "МЦЕЛЛ2") or 1e9)

# Слова подписи = всё на стр.1 ВЫШЕ тела и НИЖЕ номера страницы (номер у верха).
# Номер страницы «1» стоит на самом верху (yMin≈56). Отсекаем по x: подпись
# занимает основную ширину, номер — узкий по центру вверху. Берём слова между
# заголовком раздела и телом таблицы.
y_head = h.y_of(pdf, "Раздел")  # верх страницы
cap = [w for w in ws if w[0] == 1 and w[2] > y_head and w[2] < y_body_top]
assert cap, "не найдены слова подписи"

# распределяем по строкам через yMax (строки различаются на ~24pt)
rows = sorted(set(round(w[4], 0) for w in cap))
n_lines = len(rows)
cap_last_ymax = max(w[4] for w in cap)
gap = y_body_top - cap_last_ymax

c.check("caption_multiline", n_lines >= 3,
        f"подпись заняла {n_lines} строк (<3): {rows} — недостаточно для теста")

c.check("no_overlap", gap > 0,
        f"НАЕЗД подписи на тело: последняя строка подписи yMax={cap_last_ymax:.1f}, "
        f"первая строка тела yMin={y_body_top:.1f}, зазор={gap:.1f} (ожидал >0). "
        f"Файл: h2_caption_multiline_no_overlap.typ")

# Зазор не должен быть и подозрительно микроскопическим (хотя бы пара pt).
c.check("gap_reasonable", gap > 2,
        f"зазор подпись→тело всего {gap:.1f}pt — практически впритык, риск наезда")

c.done()
