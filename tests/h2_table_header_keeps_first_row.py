"""h2 ТАБЛИЦЫ #1: заголовок таблицы НЕ должен висеть один без первой строки данных.

ГОСТ/типографика: разрывать таблицу так, чтобы шапка («Таблица N – ...» +
строка-заголовок столбцов) оставалась на странице БЕЗ единой строки тела —
недопустимо (orphan header). Если шапка влезла внизу страницы, а первая
строка данных нет — обе должны были уехать вместе на следующую страницу.

Геометрия (pt, pdftotext -bbox): верх тела yMin≈56.3, низ тела yMax≈786,
номер страницы yMin≈801.8. #v(650pt) выталкивает шапку к нижнему полю.

ИНВАРИАНТ: подпись «Таблица», строка-шапка «Заголовок» и первая строка
данных «СТРОКА1» — на ОДНОЙ странице.
"""
import helpers as h

c = h.Checks("h2_table_header_keeps_first_row")
pdf = h.compile("h2_table_header_keeps_first_row.typ")
ws = h.words(pdf)


def page_of(word):
    hits = [w for w in ws if w[5] == word]
    return hits[0][0] if hits else None


p_cap = page_of("Таблица")        # подпись фигуры
p_colhdr = page_of("Заголовок")   # строка-шапка столбцов (первая строка table())
p_row1 = page_of("СТРОКА1")       # первая числовая строка данных

# 0) предусловие: таблица реально разорвана на >=2 страницы
c.check("multipage", h.page_count(pdf) >= 2,
        f"таблица не разорвалась: {h.page_count(pdf)} стр. — тест бессмыслен")

# 1) подпись и строка-шапка столбцов на одной странице (это сама шапка)
c.check("caption_with_colheader", p_cap is not None and p_cap == p_colhdr,
        f"подпись и шапка столбцов разъехались: Таблица=стр{p_cap} Заголовок=стр{p_colhdr}")

# 2) ГЛАВНЫЙ инвариант: первая строка данных на той же странице, что и шапка.
#    Если FAIL — шапка осталась сиротой внизу страницы без данных.
c.check("header_keeps_first_row", p_colhdr is not None and p_row1 == p_colhdr,
        f"ШАПКА-СИРОТА: строка-шапка «Заголовок» на стр{p_colhdr}, "
        f"а первая строка данных «СТРОКА1» уехала на стр{p_row1}. "
        f"Ожидал: обе на одной странице (шапка не должна висеть одна). "
        f"Файл: h2_table_header_keeps_first_row.typ "
        f"(figure.typ: table.header не удерживается с первой строкой тела)")

# 3) подпись таблицы тоже должна быть с первой строкой данных
c.check("caption_keeps_first_row", p_cap is not None and p_row1 == p_cap,
        f"подпись «Таблица 1» на стр{p_cap}, данные «СТРОКА1» на стр{p_row1} — оторваны")

c.done()
