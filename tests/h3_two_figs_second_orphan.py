"""h3 РИСУНКИ: из двух рисунков ВТОРОЙ стоит у границы страницы — его подпись НЕ отрывается.

Рис.1 наверху, затем #v(13cm) выталкивает рис.2 к низу стр.1: тело ВТОРТЕЛО
(rect 7cm×5cm) ещё влезает на стр.1, но «Рисунок 2» уже нет. По ГОСТ рисунок и
подпись неразрывны — обязаны быть вместе (перенестись на стр.2 целиком).

Тело rect бестекстовое → страницу тела ловим по метке ВТОРТЕЛО внутри прямоугольника.
Подпись второго рисунка — это слово «Рисунок» со следующим за ним номером «2».

ИЗВЕСТНЫЙ БАГ (figure kind:image: body / v / caption — три отдельных блока):
ожидается FAIL — «Рисунок 2» осиротеет на стр.2, тело останется на стр.1.

ИНВАРИАНТЫ:
  1. в документе ровно две подписи «Рисунок», нумерация рис.1='1', рис.2='2';
  2. КЛЮЧЕВОЙ: тело ВТОРТЕЛО и подпись «Рисунок 2» на ОДНОЙ странице;
  3. подпись рис.2 ниже своего тела (если вместе) — корректный порядок.
"""
import helpers as h

c = h.Checks("h3_two_figs_second_orphan")
pdf = h.compile("h3_two_figs_second_orphan.typ")
ws = h.words(pdf)

caps = [w for w in ws if w[5] == "Рисунок"]
body2 = [w for w in ws if w[5] == "ВТОРТЕЛО"]


def number_after(cap):
    same_line = [w for w in ws if w[0] == cap[0] and abs(w[2] - cap[2]) < 2.0
                 and w[1] > cap[3] and w[5] in ("1", "2", "3")]
    same_line.sort(key=lambda w: w[1])
    return same_line[0][5] if same_line else None


c.check("two_captions_and_body", len(caps) == 2 and len(body2) == 1,
        f"подписей «Рисунок»={len(caps)} (ожид.2), метка ВТОРТЕЛО={len(body2)} (ожид.1)")

if len(caps) == 2 and len(body2) == 1:
    cap2 = caps[1]          # вторая подпись в документ-ордере
    b2 = body2[0]
    # 1. нумерация сквозная: первая='1', вторая='2'
    nums = [number_after(caps[0]), number_after(cap2)]
    c.check("numbering_1_2", nums == ["1", "2"],
            f"номера = {nums}, ожидалось ['1','2']")
    # 2. КЛЮЧЕВОЙ ИНВАРИАНТ: тело и подпись второго рисунка на одной странице
    c.check("second_fig_same_page", b2[0] == cap2[0],
            f"ОТРЫВ ПОДПИСИ РИС.2: тело ВТОРТЕЛО на стр.{b2[0]} (y={b2[2]:.1f}), "
            f"«Рисунок 2» на стр.{cap2[0]} (y={cap2[2]:.1f}). Второй рисунок у границы "
            f"страницы разорван: body/v/caption — отдельные блоки без block(breakable:false).")
    # 3. при совместном расположении подпись ниже тела
    if b2[0] == cap2[0]:
        c.check("second_caption_below_body", cap2[2] > b2[4],
                f"подпись рис.2 yMin={cap2[2]:.1f} не ниже тела yMax={b2[4]:.1f}")
    else:
        c.check("second_caption_below_body", False,
                "порядок не проверить: подпись рис.2 на другой странице (см. выше)")

c.done()
