"""h4_deep_nesting_4lvl: четыре вложенных уровня «= Альфа / == Бета /
=== Гамма / ==== Дельта» нумеруются строго иерархически: 1, 1.1, 1.1.1.

Четвёртый уровень: пакет фактически нумерует его как «1.1.1.1» (а не
оставляет ненумерованным). Это поведение фиксируем явной проверкой, чтобы
регрессия в любую сторону (пропавший номер ИЛИ сбитая иерархия) была видна.

Жёсткость: точные строки «N... Заголовок» из текстового слоя, плюс контроль,
что номера не «съехали» (нет ложных 2/1.2/1.1.2 — счётчики каждого уровня
инкрементятся независимо и не протекают между уровнями).
"""
import helpers as h

c = h.Checks("h4_deep_nesting_4lvl")
pdf = h.compile("h4_deep_nesting_4lvl.typ")
t = h.text(pdf)

# Уровни 1..3 — каноничная нумерация ГОСТ.
c.check("lvl1_2_3_exact",
        "1 Альфа" in t and "1.1 Бета" in t and "1.1.1 Гамма" in t,
        f"нумерация ур.1-3 нарушена:\n{t[:400]!r}")

# Уровень 4: пакет нумерует его как 1.1.1.1 (зафиксированное поведение).
# Если регрессия сделает его ненумерованным — упадёт здесь с деталями.
lvl4_numbered = "1.1.1.1 Дельта" in t
lvl4_plain = ("Дельта" in t) and not lvl4_numbered
c.check("lvl4_numbered_1_1_1_1",
        lvl4_numbered,
        f"4-й уровень НЕ '1.1.1.1 Дельта'. "
        f"{'он ненумерован (== поведение изменилось)' if lvl4_plain else 'Дельта вовсе пропала'}:\n{t[:400]!r}")

# Иерархия не протекает: первый и единственный раздел остаётся '1',
# не появляется ложного '2 ', '1.2 ', '1.1.2 ' (счётчики не задвоились).
import re
bad = [m for m in re.findall(r"\b2 Альфа|\b1\.2 Бета|\b1\.1\.2 Гамма", t)]
c.check("no_counter_leak",
        "2 Альфа" not in t and "1.2 Бета" not in t and "1.1.2 Гамма" not in t,
        f"счётчик протёк между уровнями, лишние номера: {bad}\n{t[:400]!r}")

c.done()
