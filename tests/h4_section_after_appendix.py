"""h4_section_after_appendix: раздел → приложение → снова раздел. Приложение
НЕ должно сбивать сквозной счётчик разделов: «Первый»=1, «Второй»=2, после
приложения «Третий»=3.

Жёсткость: точные строки «N Раздел» из текстового слоя + явный запрет на
обнулённый счётчик («1 Третий раздел»). Приложение проверяем отдельно —
его заголовок «ПРИЛОЖЕНИЕ А» не нумеруется как раздел.

ВНИМАНИЕ — ОЖИДАЕМЫЙ БАГ: текущая dev-версия после show-rule `приложение`
обнуляет счётчик heading, и «Третий раздел» получает номер «1» вместо «3».
Тест намеренно требует ГОСТ-корректного «3 Третий раздел» и должен УПАСТЬ,
пока баг не исправлен. Это не подгонка под реализацию — это фиксация дефекта.
"""
import helpers as h

c = h.Checks("h4_section_after_appendix")
pdf = h.compile("h4_section_after_appendix.typ")
t = h.text(pdf)

# Разделы до приложения нумеруются 1 и 2.
c.check("before_appendix_1_2",
        "1 Первый раздел" in t and "2 Второй раздел" in t,
        f"разделы до приложения не 1/2:\n{t[:500]!r}")

# Заголовок приложения присутствует и не пронумерован как раздел.
c.check("appendix_heading_not_section",
        "ПРИЛОЖЕНИЕ А" in t and "3 ПРИЛОЖЕНИЕ" not in t,
        f"заголовок приложения отсутствует или пронумерован как раздел:\n{t[:600]!r}")

# Ключевая проверка ГОСТ: раздел после приложения = 3, НЕ обнулён до 1.
c.check("section_after_appendix_is_3",
        "3 Третий раздел" in t and "1 Третий раздел" not in t,
        "БАГ: приложение сбило счётчик разделов — "
        f"'3 Третий раздел' нет, а '1 Третий раздел'={'есть' if '1 Третий раздел' in t else 'нет'}:\n{t[:600]!r}")

c.done()
