"""h4_section_after_appendix: раздел → приложение → снова раздел.

By-design: приложение имеет СВОЮ нумерацию и обнуляет счётчик разделов —
раздел после приложения получает «1». Это НЕ баг (приложения по ГОСТ идут
в конце документа, разделов после них не бывает; reset подтверждён как
ожидаемое поведение). Структурные элементы (ВВЕДЕНИЕ и т.п.) счётчик НЕ
сбрасывают — это проверяется в hd5_*.
"""
import helpers as h

c = h.Checks("h4_section_after_appendix")
pdf = h.compile("h4_section_after_appendix.typ")
t = h.text(pdf)

# Разделы до приложения нумеруются 1 и 2.
c.check("before_appendix_1_2",
        "1 Первый раздел" in t and "2 Второй раздел" in t,
        f"разделы до приложения не 1/2:\n{t[:500]!r}")

# Заголовок приложения присутствует и не пронумерован как раздел.
c.check("appendix_heading_not_section",
        "ПРИЛОЖЕНИЕ А" in t and "3 ПРИЛОЖЕНИЕ" not in t,
        f"заголовок приложения отсутствует или пронумерован как раздел:\n{t[:600]!r}")

# By-design: приложение обнуляет счётчик (своя нумерация) → раздел после = 1.
c.check("appendix_resets_counter_by_design",
        "1 Третий раздел" in t,
        f"раздел после приложения должен получить «1» (приложение со своей "
        f"нумерацией обнуляет счётчик):\n{t[:600]!r}")

c.done()
