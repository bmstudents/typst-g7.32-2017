"""h4_struct_center_exact: структурный заголовок «= ВВЕДЕНИЕ» центрируется
по ГОРИЗОНТАЛИ строго в центре текстового поля, а НЕ прижат к левому полю.

Геометрия (из пакета): левое поле ≈ 85, правый край текстового поля ≈ 552.8,
центр cx ≈ 319. Слово ВВЕДЕНИЕ имеет ненулевую ширину, поэтому его x0 заметно
правее левого поля. Жёсткость: окно центра узкое [304..334] (а не «>150»),
плюс отдельная проверка, что левый край слова НЕ совпадает с левым полем 85
(иначе заголовок просто выровнен влево, а тест-на-центр ложно прошёл бы).
"""
import helpers as h

c = h.Checks("h4_struct_center_exact")
pdf = h.compile("h4_struct_center_exact.typ")
vv = [w for w in h.words(pdf) if w[5] == "ВВЕДЕНИЕ"]

c.check("exactly_one_vvedenie",
        len(vv) == 1,
        f"ждём ровно одно слово ВВЕДЕНИЕ, нашли {len(vv)}: {vv}")

if vv:
    x0, x1 = vv[0][1], vv[0][3]
    cx = (x0 + x1) / 2
    # Центр в узком окне вокруг центра поля 319.
    c.check("center_in_304_334",
            304.0 <= cx <= 334.0,
            f"cx={cx:.2f} вне окна [304..334] (центр поля 319). x0={x0:.1f} x1={x1:.1f}")
    # Не прижат к левому полю (≈85): иначе это не центрирование.
    c.check("not_left_margin",
            x0 > 200.0,
            f"x0={x0:.1f} близко к левому полю 85 — заголовок не центрирован")
else:
    c.check("center_in_304_334", False, "нет ВВЕДЕНИЕ")
    c.check("not_left_margin", False, "нет ВВЕДЕНИЕ")

c.done()
