"""h4_struct_no_number_then_section: ненумерованный структурный «= ВВЕДЕНИЕ»
НЕ тратит счётчик разделов — следующий обычный «= Анализ» получает номер «1».

Жёсткость:
  1) ВВЕДЕНИЕ присутствует и НЕ пронумерован (нет «1 ВВЕДЕНИЕ»/«2 ВВЕДЕНИЕ»).
  2) «Анализ» нумеруется именно «1 Анализ» (счётчик стартует с 1).
  3) Запрет «2 Анализ» — отдельная проверка: ловит обратную ошибку, когда
     структурный заголовок ошибочно инкрементнул счётчик до 2.
"""
import helpers as h

c = h.Checks("h4_struct_no_number_then_section")
pdf = h.compile("h4_struct_no_number_then_section.typ")
t = h.text(pdf)

c.check("vvedenie_unnumbered",
        "ВВЕДЕНИЕ" in t and "1 ВВЕДЕНИЕ" not in t and "2 ВВЕДЕНИЕ" not in t,
        f"ВВЕДЕНИЕ пропал или получил номер:\n{t[:400]!r}")

c.check("section_is_1",
        "1 Анализ" in t,
        f"раздел после структурного не получил номер 1:\n{t[:400]!r}")

c.check("section_not_2",
        "2 Анализ" not in t,
        f"раздел получил номер 2 — структурный ВВЕДЕНИЕ съел счётчик:\n{t[:400]!r}")

c.done()
