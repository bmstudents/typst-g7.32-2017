"""h5_enum_paren_not_dot: маркеры нумерованного списка — «1)» «2)» «3)» со скобкой
(как требует ГОСТ 7.32 для перечислений), а НЕ точечные «1.» «2.» «3.».

Жёсткость: тела пунктов намеренно БЕЗ цифр и точек, поэтому любой найденный токен
«N)» или «N.» может прийти ТОЛЬКО от маркера перечисления. Это делает негативную
проверку (отсутствие точечных маркеров) точной, без ложных срабатываний на текст.
Проверяем и токены координатного слоя, и текстовый слой.
"""
import re
import helpers as h

c = h.Checks("h5_enum_paren_not_dot")
pdf = h.compile("h5_enum_paren_not_dot.typ")
W = h.words(pdf)
t = h.text(pdf)
toks = {w[5] for w in W}

# Скобочные маркеры присутствуют как отдельные токены координатного слоя.
c.check("paren_markers_present",
        {"1)", "2)", "3)"} <= toks,
        f"нет полного набора скобочных маркеров; токены: {sorted(toks)}")

# Точечных маркеров «N.» в координатном слое быть не должно
# (тела пунктов без цифр, значит «1.» мог бы быть только маркером).
dot_tokens = sorted(tk for tk in toks if re.match(r"^\d+\.$", tk))
c.check("no_dot_markers_in_layer", not dot_tokens,
        f"найдены точечные маркеры-токены {dot_tokens} вместо скобочных")

# В текстовом слое нет последовательностей «1.» «2.» «3.» как маркеров.
c.check("no_dot_numbering_in_text",
        not re.search(r"\b[123]\.\s", t) and "1." not in t.replace("(1)", ""),
        f"встречена точечная нумерация в тексте:\n{t!r}")

c.done()
