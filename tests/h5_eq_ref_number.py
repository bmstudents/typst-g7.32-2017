"""h5_eq_ref_number: $x=1$ <e1> + ссылка @e1 → ссылка раскрывается в «(1)».
Минимум 2 вхождения «(1)»: сам номер формулы + раскрытая ссылка.

Жёсткость: считаем точное число вхождений «(1)» (== 2: номер + ссылка), проверяем,
что ссылка раскрылась РЯДОМ с уникальным маркером «РЕФМЕТКА» (а не где попало), и
что метка НЕ осталась сырой («@e1»/«e1»/«???»). Маркер «РЕФМЕТКА» уникален в тексте,
поэтому привязка точная.
"""
import re
import helpers as h

c = h.Checks("h5_eq_ref_number")
pdf = h.compile("h5_eq_ref_number.typ")
t = h.text(pdf)

# Ровно 2 вхождения «(1)»: номер у формулы и раскрытая ссылка.
count = t.count("(1)")
c.check("two_occurrences", count == 2,
        f"ожидали ровно 2 вхождения «(1)» (номер формулы + ссылка), найдено {count}:\n{t!r}")

# Ссылка @e1 раскрылась в «(1)» вплотную к уникальному маркеру «РЕФМЕТКА».
c.check("ref_resolved_at_marker",
        re.search(r"РЕФМЕТКА\s*\(1\)", t) is not None,
        f"ссылка @e1 не раскрылась в «(1)» рядом с маркером «РЕФМЕТКА»:\n{t!r}")

# Метка не осталась сырой/битой.
c.check("no_raw_label",
        "@e1" not in t and "e1" not in t and "???" not in t,
        f"метка осталась нераскрытой («@e1»/«e1»/«???»):\n{t!r}")

c.done()
