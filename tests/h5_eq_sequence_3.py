"""h5_eq_sequence_3: три блочные формулы → нумеруются «(1)» «(2)» «(3)» строго по
порядку сверху вниз (y растёт), каждый номер ровно по одному разу.

Жёсткость: проверяем не только наличие, но и (а) уникальность каждого номера,
(б) строгий вертикальный порядок по y, (в) все три номера на одном x-краю
(выровнены по правому полю).
"""
import helpers as h

c = h.Checks("h5_eq_sequence_3")
pdf = h.compile("h5_eq_sequence_3.typ")
W = h.words(pdf)

def occ(tok):
    return [w for w in W if w[5] == tok]

o1, o2, o3 = occ("(1)"), occ("(2)"), occ("(3)")

# Каждый номер ровно один раз.
c.check("each_once",
        len(o1) == 1 and len(o2) == 1 and len(o3) == 1,
        f"номера встречаются не по разу: |(1)|={len(o1)} |(2)|={len(o2)} |(3)|={len(o3)}")

if o1 and o2 and o3:
    y1, y2, y3 = o1[0][2], o2[0][2], o3[0][2]
    # Строгий порядок сверху вниз.
    c.check("vertical_order", y1 < y2 < y3,
            f"порядок номеров по y нарушен: (1)@{y1:.1f} (2)@{y2:.1f} (3)@{y3:.1f}")

    # Все три номера прижаты к одному правому краю (разброс x1 < 1pt).
    x1s = [o1[0][3], o2[0][3], o3[0][3]]
    c.check("same_right_edge", max(x1s) - min(x1s) < 1.0,
            f"номера не на одном правом краю: x1={[round(x,2) for x in x1s]}")

    # И этот край за 540 (у правого поля).
    c.check("at_right_margin", min(x1s) > 540,
            f"правый край номеров {min(x1s):.2f} ≤ 540 — не прижаты к полю")

c.done()
