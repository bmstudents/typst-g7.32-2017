"""h6: два рисунка в приложении А, буква-в-иллюстрациях:да —
подписи нумеруются 'Рисунок А.1' и 'Рисунок А.2' (буква.номер), причём
номер сбрасывается на 1 внутри приложения и инкрементируется.

Жёсткие инварианты:
  1. в тексте ровно один 'Рисунок А.1' и ровно один 'Рисунок А.2';
  2. НЕТ голого 'Рисунок 1'/'Рисунок 2' без буквы и нет 'Рисунок А.3'
     (счётчик не убежал);
  3. подпись с телом 'Альфа-схема' (А.1) расположена выше подписи
     'Бета-схема' (А.2) по координате — порядок нумерации совпадает с
     физическим порядком.
"""
import helpers as h

c = h.Checks("h6_appendix_figure_letter_exact")
pdf = h.compile("h6_appendix_figure_letter_exact.typ")
norm = " ".join(h.text(pdf).split())

# 1. ровно по одному "Рисунок А.1" и "Рисунок А.2"
n1 = norm.count("Рисунок А.1")
n2 = norm.count("Рисунок А.2")
c.check("a1_once", n1 == 1, f"'Рисунок А.1' встречается {n1} раз, ожидалось 1")
c.check("a2_once", n2 == 1, f"'Рисунок А.2' встречается {n2} раз, ожидалось 1")

# 2. нет голых подписей без буквы и нет лишнего А.3
import re
# "Рисунок 1"/"Рисунок 2" как отдельный токен (за номером не идёт точка-буква)
bare = re.findall(r"Рисунок (\d)\b", norm)
c.check("no_bare_number", bare == [],
        f"найдены подписи без буквы приложения: {bare} (ожидалось пусто) в:\n{norm[:300]}")
c.check("no_a3", "Рисунок А.3" not in norm,
        "счётчик рисунков в приложении убежал: появился 'Рисунок А.3'")

# 3. А.1 (Альфа-схема) выше А.2 (Бета-схема) по (page, y)
def pos(word):
    hits = sorted([(w[0], w[2]) for w in h.words(pdf) if w[5] == word])
    return hits[0] if hits else None

p_alpha = pos("Альфа-схема")
p_beta = pos("Бета-схема")
c.check("both_captions_located", p_alpha is not None and p_beta is not None,
        f"не нашёл подписи: Альфа={p_alpha} Бета={p_beta}")
if p_alpha is not None and p_beta is not None:
    c.check("a1_above_a2", p_alpha < p_beta,
            f"А.1 'Альфа-схема' {p_alpha} должна быть выше А.2 'Бета-схема' {p_beta}")
c.done()
