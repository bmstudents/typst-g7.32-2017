"""h6: документ с 3 рисунками и 2 таблицами, перемешанными в одном разделе.
Счётчики #колво-рисунков и #колво-таблиц должны давать РОВНО 3 и 2 —
счётчики kind=image и kind=table не пересекаются.

Жёсткие инварианты:
  1. #колво-рисунков == 3 (точное равенство, не >=);
  2. #колво-таблиц == 2 (точное равенство);
  3. сами объекты отрендерены: 'Рисунок 3' и 'Таблица 2' есть, а
     'Рисунок 4'/'Таблица 3' — нет (счётчики не перепутаны и не убежали).
"""
import re
import helpers as h

c = h.Checks("h6_counters_exact")
pdf = h.compile("h6_counters_exact.typ")
norm = " ".join(h.text(pdf).split())

mf = re.search(r"маркерР\s+(\d+)\s+маркерР", norm)
mt = re.search(r"маркерТ\s+(\d+)\s+маркерТ", norm)
vf = int(mf.group(1)) if mf else None
vt = int(mt.group(1)) if mt else None

c.check("figures_eq_3", vf == 3,
        f"#колво-рисунков = {vf}, ожидалось ровно 3 (текст: {norm[:200]})")
c.check("tables_eq_2", vt == 2,
        f"#колво-таблиц = {vt}, ожидалось ровно 2 (текст: {norm[:200]})")

# 3. объекты отрендерены и счётчики не убежали / не перепутаны
c.check("fig3_table2_present", "Рисунок 3" in norm and "Таблица 2" in norm,
        f"нет 'Рисунок 3' и/или 'Таблица 2' в:\n{norm[:400]}")
c.check("no_overflow", "Рисунок 4" not in norm and "Таблица 3" not in norm,
        f"счётчик убежал: появился 'Рисунок 4' или 'Таблица 3':\n{norm[:400]}")
c.done()
