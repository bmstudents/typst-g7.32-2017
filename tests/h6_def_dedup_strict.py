"""h6: один и тот же термин #определение использован ДВАЖДЫ (с разными
фразами-ссылками 'кэшбекинг', но одинаковым текстом определения) — в разделе
определений запись появляется РОВНО один раз.

Конструкция теста разделяет inline-ссылку и текст определения:
  - 'кэшбекинг'  — фраза-ссылка, рендерится в теле дважды (оба #определение);
  - 'Зетамаркер' — уникальный маркер ТЕКСТА определения; он не встречается
    в теле, только в сгенерированном разделе.

Жёсткие инварианты:
  1. фраза-ссылка 'кэшбекинг' встречается ровно 2 раза (оба inline-вхождения
     отрендерены, ни одно не схлопнуто);
  2. маркер текста определения 'Зетамаркер' встречается РОВНО 1 раз во всём
     документе — дедуп в разделе сработал, дубликата нет;
  3. сам текст определения (хвост) тоже ровно 1 раз.
"""
import helpers as h

c = h.Checks("h6_def_dedup_strict")
pdf = h.compile("h6_def_dedup_strict.typ")
norm = " ".join(h.text(pdf).split())

# 1. inline-ссылка отрендерена дважды
n_ref = norm.count("кэшбекинг")
c.check("ref_rendered_twice", n_ref == 2,
        f"inline-ссылка 'кэшбекинг' встречается {n_ref} раз, ожидалось 2 "
        f"(оба #определение должны отрендерить текст-ссылку)")

# 2. маркер текста определения ровно 1 раз -> дедуп
n_mark = norm.count("Зетамаркер")
c.check("definition_dedup", n_mark == 1,
        f"БАГ ДЕДУПА: маркер текста определения 'Зетамаркер' встречается {n_mark} раз, "
        f"ожидалось ровно 1 (термин дважды -> в разделе один раз):\n{norm[:500]}")

# 3. хвост текста определения тоже ровно 1 раз
n_tail = norm.count("механизм отложенной валидации транзакций")
c.check("definition_body_once", n_tail == 1,
        f"тело определения встречается {n_tail} раз, ожидалось 1")
c.done()
