"""h6: три определения, тексты которых начинаются на В, А, Б, ВВЕДЕНЫ
именно в этом порядке (В, А, Б). В разделе они должны идти по алфавиту
кириллицы: А, Б, В — то есть Антиксельтерм, Биксельтерм, Виксельтерм.

Сортировка в definitions.typ идёт по тексту определения (2-й аргумент),
поэтому маркеры подобраны так, что алфавитный порядок текстов = А<Б<В,
а порядок ВВОДА в .typ обратный по первой букве (В, А, Б).

Жёсткие инварианты:
  1. все три маркера присутствуют ровно по разу (ref-фразы отличаются, текст
     попадает только в раздел);
  2. координаты найдены, все на одной странице раздела;
  3. строгий порядок по (page, y): Антиксельтерм < Биксельтерм < Виксельтерм
     (А выше Б выше В), несмотря на порядок ввода В, А, Б.
"""
import helpers as h

c = h.Checks("h6_def_sorted_cyrillic")
pdf = h.compile("h6_def_sorted_cyrillic.typ")
norm = " ".join(h.text(pdf).split())

for marker in ("Антиксельтерм", "Биксельтерм", "Виксельтерм"):
    n = norm.count(marker)
    c.check(f"once_{marker}", n == 1, f"маркер {marker!r} встречается {n} раз, ожидалось 1")

def pos(word):
    hits = sorted([(w[0], w[2]) for w in h.words(pdf) if w[5] == word])
    return hits[0] if hits else None

pa = pos("Антиксельтерм")  # А
pb = pos("Биксельтерм")    # Б
pv = pos("Виксельтерм")    # В

c.check("coords_found", None not in (pa, pb, pv),
        f"не нашёл координаты: А={pa} Б={pb} В={pv}")

if None not in (pa, pb, pv):
    c.check("alpha_order_A_B_V", pa < pb < pv,
            f"порядок в разделе должен быть А<Б<В по (page,y): "
            f"А={pa}, Б={pb}, В={pv} (введены были как В,А,Б)")
c.done()
