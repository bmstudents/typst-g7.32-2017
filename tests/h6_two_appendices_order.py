"""h6: два приложения А и Б, каждое в своём #[ ] со своим show.

Жёсткие инварианты:
  1. оба заголовка 'ПРИЛОЖЕНИЕ А' и 'ПРИЛОЖЕНИЕ Б' присутствуют РОВНО по одному
     разу (заголовок не дублируется, лишних приложений нет);
  2. слово 'ПРИЛОЖЕНИЕ' встречается ровно дважды во всём документе;
  3. титул 'ПРИЛОЖЕНИЕ А' строго выше титула 'ПРИЛОЖЕНИЕ Б' — либо на меньшей
     странице, либо (если на одной) с меньшим y. Сравниваем как (page, y),
     а не только y, чтобы порядок был корректен при разнесении по страницам.
"""
import helpers as h

c = h.Checks("h6_two_appendices_order")
pdf = h.compile("h6_two_appendices_order.typ")
norm = " ".join(h.text(pdf).split())

# 1. оба заголовка ровно по разу
na = norm.count("ПРИЛОЖЕНИЕ А")
nb = norm.count("ПРИЛОЖЕНИЕ Б")
c.check("each_title_once", na == 1 and nb == 1,
        f"заголовки приложений не по одному разу: 'ПРИЛОЖЕНИЕ А'={na}, 'ПРИЛОЖЕНИЕ Б'={nb}")

# 2. ровно два слова 'ПРИЛОЖЕНИЕ' (нет лишних/потерянных приложений)
c.check("exactly_two_appendices", norm.count("ПРИЛОЖЕНИЕ") == 2,
        f"слово 'ПРИЛОЖЕНИЕ' встречается {norm.count('ПРИЛОЖЕНИЕ')} раз, ожидалось 2")

# 3. А строго выше Б по (page, y). Слово 'ПРИЛОЖЕНИЕ' идёт перед буквой,
#    берём координаты самих букв 'А' и 'Б' как заголовков приложений.
def pos(word):
    hits = [(w[0], w[2]) for w in h.words(pdf) if w[5] == word]
    return hits[0] if hits else None

# Координаты заголовочного слова 'ПРИЛОЖЕНИЕ': 1-е = А-приложение, 2-е = Б.
prilozh = sorted([(w[0], w[2]) for w in h.words(pdf) if w[5] == "ПРИЛОЖЕНИЕ"])
c.check("two_title_coords", len(prilozh) == 2,
        f"нашлось {len(prilozh)} координат слова 'ПРИЛОЖЕНИЕ', ожидалось 2")

if len(prilozh) == 2:
    first, second = prilozh[0], prilozh[1]
    c.check("A_above_B", first < second,
            f"'ПРИЛОЖЕНИЕ А' (page,y)={first} должно быть выше 'ПРИЛОЖЕНИЕ Б' {second}")
c.done()
