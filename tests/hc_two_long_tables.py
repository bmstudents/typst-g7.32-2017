"""Две длинные таблицы подряд (обе переносятся): continuation-счётчик
сбрасывается между ними. Первая → «Продолжение таблицы 1», вторая →
«Таблица 2» и «Продолжение таблицы 2». Вторая НЕ должна ложно начинаться с
«Продолжение» (счётчик continuation должен сброситься после первой)."""
import re
import helpers as h

c = h.Checks("hc_two_long_tables")
pdf = h.compile("hc_two_long_tables.typ")
norm = " ".join(h.text(pdf).split())

c.check("both_numbered", "Таблица 1" in norm and "Таблица 2" in norm,
        f"нет обоих номеров: {norm[:160]}")
c.check("cont1_present", "Продолжение таблицы 1" in norm, "нет продолжения первой")
c.check("cont2_present", "Продолжение таблицы 2" in norm, "нет продолжения второй")
# вторая таблица начинается как «Таблица 2», а не как продолжение первой:
# в тексте «Таблица 2» должна встретиться раньше второго блока продолжений
idx_t2 = norm.find("Таблица 2")
idx_c1_last = norm.rfind("Продолжение таблицы 1")
c.check("table2_starts_fresh", idx_t2 != -1 and idx_t2 > idx_c1_last,
        "«Таблица 2» не появляется как свежий заголовок после продолжений первой")
c.done()
