"""hd3: все пять счётчиков реферата в одном документе (необычная комбинация).

Основная часть: 2 рисунка, 2 таблицы, 2 цитируемых источника.
Приложение А: ещё 1 рисунок + 1 таблица (нумеруются заново как А.1 — в
реферат основной части не входят). Всего 3 приложения (А, Б, В).

Ожидаем:
  #колво-рисунков == 2  (приложенческий не считается)
  #колво-таблиц   == 2  (приложенческая не считается)
  #колво-источников == 2
  #колво-приложений == 3
  #колво-страниц == фактическое число физических страниц pdf
"""
import re
import helpers as h

c = h.Checks("hd3_cnt_all_combined")
pdf = h.compile("hd3_cnt_all_combined.typ")
t = " ".join(h.text(pdf).split())

def grab(mark):
    m = re.search(mark + r"\s+(\d+)\s+" + mark, t)
    return int(m.group(1)) if m else None

P, F, T, S, A = (grab(x) for x in ("mP", "mF", "mT", "mS", "mA"))

c.check("all_emitted", None not in (P, F, T, S, A),
        f"не все счётчики извлечены: P={P} F={F} T={T} S={S} A={A}\n{t[:300]}")

c.check("figures_main_only", F == 2,
        f"#колво-рисунков = {F}, ожидалось 2 (приложенческий рисунок не входит)")
c.check("tables_main_only", T == 2,
        f"#колво-таблиц = {T}, ожидалось 2 (приложенческая таблица не входит)")
c.check("sources_2", S == 2,
        f"#колво-источников = {S}, ожидалось 2")
c.check("appendices_3", A == 3,
        f"#колво-приложений = {A}, ожидалось 3")

# колво-страниц == фактическое число страниц pdf
pc = h.page_count(pdf)
c.check("pages_eq_pdf", P == pc,
        f"#колво-страниц = {P}, физических страниц pdf = {pc}")
c.done()
