"""hd3: #колво-рисунков должен считать ТОЛЬКО рисунки основной части.

3 рисунка в основной части + 2 в приложении. Реферат по ГОСТ 7.32-2017
сообщает число иллюстраций основной части (приложенческие нумеруются
заново как А.1, А.2 и в реферат не входят). Ожидаем 3.
"""
import re
import helpers as h

c = h.Checks("hd3_cnt_fig_appendix_excluded")
pdf = h.compile("hd3_cnt_fig_appendix_excluded.typ")
t = " ".join(h.text(pdf).split())

m = re.search(r"маркеррис\s+(\d+)\s+маркеррис", t)
val = int(m.group(1)) if m else None
c.check("counter_emitted", val is not None,
        f"маркер #колво-рисунков не нашёлся в:\n{t[:300]}")

# все 5 рисунков отрендерились (3 основных + 2 приложенческих А.1/А.2)
c.check("five_figures_rendered",
        t.count("Рисунок") + t.count("А.1") + t.count("А.2") >= 0
        and "Первая схема" in t and "Схема приложения один" in t,
        f"не все рисунки отрендерились:\n{t[:400]}")

# главный инвариант: счётчик считает только основную часть
c.check("counter_eq_3_main_only", val == 3,
        f"#колво-рисунков = {val}, ожидалось 3 (только основная часть; "
        f"приложенческие рисунки А.1/А.2 не входят в реферат)")
c.done()
