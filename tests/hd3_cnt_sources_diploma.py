"""hd3: реалистичный диплом — список из 5 источников, один не процитирован.

5 записей в .yml. Цитируются src1..src4 (src1 — дважды, проверка дедупа),
src5 забыт. Пакет печатает все 5 (bibliography full:true), нумеруя 1..5.
Реферат должен сообщать число источников СПИСКА = 5.

Демонстрирует серьёзность бага: автор увидит «5 источников» в списке, но
реферат укажет другое число => расхождение в нормоконтроле (TestVkr).
"""
import re
import helpers as h

c = h.Checks("hd3_cnt_sources_diploma")
pdf = h.compile("hd3_cnt_sources_diploma.typ")
t = " ".join(h.text(pdf).split())

m = re.search(r"маркеристочников\s+(\d+)\s+маркеристочников", t)
val = int(m.group(1)) if m else None
c.check("counter_emitted", val is not None, f"маркер не нашёлся:\n{t[:300]}")

# в напечатанном списке ровно 5 записей (по фамилиям/маркеру «пять»)
authors = [a in t for a in ("Антонов", "Бубнов", "Власов", "Гусев", "Денисов")]
printed = sum(authors)
c.check("five_entries_printed", printed == 5,
        f"в списке источников {printed} записей, ожидалось 5; авторы={authors}")

# нецитированный src5 ВСЁ РАВНО в списке (full:true) — нумерация дошла до 5.
c.check("uncited_src5_printed", "Денисов" in t,
        "нецитированный источник src5 не попал в список — full:true не сработал?")

# главный инвариант: счётчик == 5 (число записей списка)
c.check("counter_eq_5", val == 5,
        f"#колво-источников = {val}, но в списке использованных источников "
        f"5 записей (нумерация 1..5). Счётчик считает уникальные ЦИТАТЫ "
        f"(их 4 после дедупа src1), а не записи списка — расхождение реферата "
        f"с фактическим списком источников")
c.done()
