"""hd3: #колво-источников = число записей в списке использованных источников.

Пакет ставит bibliography(full: true) — печатаются ВСЕ записи .yml, даже
не процитированные. В .yml три записи, процитированы только две.
В реальном списке источников окажутся ВСЕ ТРИ. Реферат по ГОСТ 7.32-2017
сообщает число источников в списке = 3.

Если счётчик считает не записи списка, а уникальные ЦИТАТЫ (@key), он
вернёт 2 и разойдётся с напечатанным списком из 3 записей — это баг.
"""
import re
import helpers as h

c = h.Checks("hd3_cnt_sources_uncited")
pdf = h.compile("hd3_cnt_sources_uncited.typ")
t = " ".join(h.text(pdf).split())

m = re.search(r"маркеристочников\s+(\d+)\s+маркеристочников", t)
val = int(m.group(1)) if m else None
c.check("counter_emitted", val is not None,
        f"маркер #колво-источников не нашёлся в:\n{t[:300]}")

# доказываем, что в напечатанном списке источников реально 3 записи:
# у нумерованной библиографии gost-r-705 каждая запись начинается с N.
authors = ("Кузнецов" in t, "Морозова" in t, "Сидоров" in t)
printed = sum(authors)
c.check("three_entries_printed", printed == 3,
        f"в напечатанном списке источников {printed} записей, ожидалось 3 "
        f"(full:true печатает и нецитированные); авторы={authors}")

# главный инвариант: счётчик == число записей списка
c.check("counter_eq_3_entries", val == 3,
        f"#колво-источников = {val}, но в списке источников 3 записи. "
        f"Счётчик должен отражать число источников в списке, а не число "
        f"уникальных цитат")
c.done()
