"""hd3: #колво-таблиц при таблице с продолжением.

Длинная таблица переносится через несколько страниц (рендерится
«Продолжение таблицы 1»). Это всё равно ОДНА таблица. Вместе с короткой
второй ожидаем #колво-таблиц == 2, а НЕ число частей/продолжений.
"""
import re
import helpers as h

c = h.Checks("hd3_cnt_tables_continuation")
pdf = h.compile("hd3_cnt_tables_continuation.typ")
t = " ".join(h.text(pdf).split())

m = re.search(r"маркертабл\s+(\d+)\s+маркертабл", t)
val = int(m.group(1)) if m else None
c.check("counter_emitted", val is not None,
        f"маркер #колво-таблиц не нашёлся в:\n{t[:300]}")

# доказываем что таблица действительно перенеслась (есть продолжение)
c.check("continuation_present", "Продолжение таблиц" in t,
        f"длинная таблица не перенеслась — тест не нагружает баг:\n{t[:400]}")

# документ многостраничный
c.check("multipage", h.page_count(pdf) >= 2,
        f"страниц {h.page_count(pdf)}, ожидалось >=2")

# главный инвариант
c.check("counter_eq_2_not_parts", val == 2,
        f"#колво-таблиц = {val}, ожидалось 2 (две таблицы; "
        f"продолжение длинной таблицы НЕ должно увеличивать счётчик)")
c.done()
