"""hd4 ФОРМУЛЫ В ПРИЛОЖЕНИИ: по ГОСТ 7.32-2017 (п.6.8.2) формулы приложения
нумеруются в пределах приложения с буквенным обозначением — (А.1), (А.2),
а НЕ сквозным номером основного текста.

Пакет в utils/appendix.typ делает:
    set figure(numbering: appendix_num)         # буквенный формат для figure
    counter(figure.where(kind: math.equation)).update(0)
но формулы рисуются через `set math.equation(numbering: "(1)")` (styles/eq.typ),
который читает СВОЙ счётчик counter(math.equation), а НЕ figure-счётчик.
Поэтому ни сброс, ни буквенный формат на формулы не действуют → ожидаем БАГ:
в приложении формулы получают сквозные (3),(4) вместо (А.1),(А.2).
"""
import re
import helpers as h

c = h.Checks("hd4_eq_appendix_letter")
pdf = h.compile("hd4_eq_appendix_letter.typ")
t = " ".join(h.text(pdf).split())

# 1. Основной текст: сквозные (1),(2) — это корректно.
c.check("body_seq",
        "(1)" in t and "(2)" in t,
        f"в основном тексте нет '(1)'/'(2)':\n{t[:400]}")

# 2. ГЛАВНОЕ: формулы приложения должны иметь буквенный формат (А.1),(А.2).
c.check("appendix_eq_A1",
        "(А.1)" in t,
        f"формула приложения не получила буквенный номер '(А.1)'.\n"
        f"ГОСТ 7.32-2017 требует нумерацию формул приложения вида (А.1).\n"
        f"Текст PDF:\n{t}")

c.check("appendix_eq_A2",
        "(А.2)" in t,
        f"вторая формула приложения не получила '(А.2)'.\nТекст PDF:\n{t}")

# 3. И сквозного номера (3) у формулы приложения быть НЕ должно.
c.check("no_seq_in_appendix",
        "(3)" not in t and "(4)" not in t,
        f"формула приложения пронумерована сквозным '(3)'/'(4)' вместо (А.1)/(А.2) — "
        f"счётчик не сброшен и буквенный формат не применён.\nТекст PDF:\n{t}")

c.done()
