"""hd4 СКВОЗНАЯ НУМЕРАЦИЯ через разделы: формула в разделе 1 = (1),
в разделе 2 = (2), в разделе 3 = (3),(4). Счётчик НЕ сбрасывается на каждом
разделе. Проверяем монотонность и порядок по странице/координатам.
"""
import re
import helpers as h

c = h.Checks("hd4_eq_through_sections")
pdf = h.compile("hd4_eq_through_sections.typ")
t = " ".join(h.text(pdf).split())

# Все номера формул в порядке появления текстового слоя.
nums = re.findall(r"\((\d+)\)", t)
c.check("four_numbers",
        nums[:4] == ["1", "2", "3", "4"],
        f"ожидали сквозные [1,2,3,4], получили {nums[:6]} (полный текст:\n{t})")

# Раздел 1 идёт раньше раздела 2; формула (2) должна быть ниже заголовка
# '2' второго раздела (по вертикали в пределах страниц/документа).
ws = h.words(pdf)
def y_doc(word, nth=1):
    # глобальная координата: (page-1)*1e6 + yMin, чтобы сравнивать сквозь страницы
    hits = [w for w in ws if w[5] == word]
    if len(hits) < nth:
        return None
    w = hits[nth - 1]
    return (w[0] - 1) * 1_000_000 + w[2]

y1 = y_doc("(1)")
y2 = y_doc("(2)")
y3 = y_doc("(3)")
y4 = y_doc("(4)")
c.check("monotonic_layout",
        None not in (y1, y2, y3, y4) and y1 < y2 < y3 < y4,
        f"номера формул не идут монотонно по документу: y=({y1},{y2},{y3},{y4})")

# Никаких повторов '(1)' (что было бы при сбросе счётчика в каждом разделе).
c.check("no_reset",
        nums.count("1") == 1,
        f"номер '(1)' встречается {nums.count('1')} раз — счётчик сбрасывается по разделам "
        f"(должна быть сквозная нумерация). Номера: {nums}")

c.done()
