"""hd4 ДВА ПРИЛОЖЕНИЯ: счётчик формул сбрасывается в каждом приложении, а
номера получают буквенный префикс приложения (ГОСТ 7.32-2017, п.6.8.2):
  основной текст: (1)
  приложение А:   (А.1), (А.2)
  приложение Б:   (Б.1)
И @ref на формулу приложения отдаёт её буквенный номер.

Текущая реализация (styles/eq.typ: set math.equation(numbering:"(1)") +
utils/appendix.typ сбрасывает не тот счётчик) даёт сквозные (1),(2),(3),(4)
и ссылки без буквы — это ожидаемый БАГ, тест должен FAIL до фикса.
"""
import re
import helpers as h

c = h.Checks("hd4_eq_two_appendices_reset")
pdf = h.compile("hd4_eq_two_appendices_reset.typ")
t = " ".join(h.text(pdf).split())

# Приложение А — буквенные номера (А.1),(А.2).
c.check("appA_letters",
        "(А.1)" in t and "(А.2)" in t,
        f"формулы приложения А не пронумерованы (А.1)/(А.2).\nТекст:\n{t}")

# Приложение Б — сброс на (Б.1) (а не продолжение).
c.check("appB_reset_letter",
        "(Б.1)" in t,
        f"формула приложения Б не получила (Б.1) (сброс счётчика + буква Б).\nТекст:\n{t}")

# Никаких сквозных (3)/(4) у формул приложений.
c.check("no_seq_3_4",
        "(3)" not in t and "(4)" not in t,
        f"формулы приложений идут сквозными (3)/(4) вместо (А.2)/(Б.1) — "
        f"счётчик формул не сбрасывается в приложении.\nТекст:\n{t}")

# Ссылка @inB внутри приложения Б = (Б.1); @inA = (А.1).
def ref_between(a, b):
    m = re.search(re.escape(a) + r"\s+(.+?)\s+" + re.escape(b), t)
    return m.group(1) if m else None

rb = ref_between("RB", "EB")
ra = ref_between("RA", "EA")
c.check("ref_appB",
        rb == "(Б.1)",
        f"@inB вернул {rb!r}, ожидалось '(Б.1)'.\nТекст:\n{t}")
c.check("ref_appA",
        ra == "(А.1)",
        f"@inA вернул {ra!r}, ожидалось '(А.1)'.\nТекст:\n{t}")

c.done()
