"""hd5: структурный элемент между нумерованными разделами не должен
обнулять нумерацию.

Инвариант: разделы образуют монотонно возрастающую сквозную
последовательность 1,2,3,4 — НЕЗАВИСИМО от вставленного между ними
структурного элемента (ЗАКЛЮЧЕНИЕ). Структурный элемент по ГОСТ не
нумеруется и не влияет на счётчик разделов.
"""
import re
import helpers as h

c = h.Checks("hd5_structural_between_sections")
pdf = h.compile("hd5_structural_between_sections.typ")
t = h.text(pdf)
norm = re.sub(r"[ \t]+", " ", t)

# Структурный элемент присутствует и не пронумерован (нет цифры
# непосредственно перед ним на той же строке).
c.check("zaklyuchenie_present",
        "ЗАКЛЮЧЕНИЕ" in norm and not re.search(r"\d+ +ЗАКЛЮЧЕНИЕ", norm),
        "ЗАКЛЮЧЕНИЕ отсутствует или пронумеровано")

# Первые два раздела (до структурного) — 1 и 2.
c.check("before_1_2",
        "1 Раздел один" in norm and "2 Раздел два" in norm,
        f"нет '1 Раздел один' / '2 Раздел два' в:\n{norm[:400]}")

# ГЛАВНЫЙ инвариант: разделы ПОСЛЕ структурного продолжают 3 и 4,
# а НЕ начинаются заново с 1/2.
m3 = re.search(r"(\d+) Раздел три", norm)
m4 = re.search(r"(\d+) Раздел четыре", norm)
n3 = int(m3.group(1)) if m3 else None
n4 = int(m4.group(1)) if m4 else None

c.check("section_three_is_3",
        n3 == 3,
        f"раздел 'Раздел три' получил номер {n3}, ожидался 3 "
        f"(структурный ЗАКЛЮЧЕНИЕ обнулил счётчик разделов)")

c.check("section_four_is_4",
        n4 == 4,
        f"раздел 'Раздел четыре' получил номер {n4}, ожидался 4")

# Сквозная монотонность всех номеров разделов.
nums = [int(m.group(1)) for m in re.finditer(r"(\d+) Раздел (?:один|два|три|четыре)", norm)]
c.check("sections_monotonic",
        nums == [1, 2, 3, 4],
        f"номера разделов {nums}, ожидалась монотонная сквозная 1,2,3,4")

c.done()
