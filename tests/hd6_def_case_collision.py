"""hd6: два определения, различающиеся ТОЛЬКО регистром, теряются при дедупе.

definition() строит ключ как lower(to_str(text)).trim() и дедуплицирует
по нему. Поэтому два разных по написанию определения

    "ОЗУ — Оперативное Запоминающее Устройство"
    "озу — оперативное запоминающее устройство"

дают ОДИН ключ "озу — оперативное запоминающее устройство" и
схлопываются: в разделе остаётся только первое, второе исчезает.

Инвариант: оба внесённых определения должны быть видимы в разделе
(дедуп обязан срабатывать лишь на ПОЛНОСТЬЮ идентичный текст, а не на
совпадение после приведения регистра — иначе это тихая потеря данных).
"""
import helpers as h

c = h.Checks("hd6_def_case_collision")
pdf = h.compile("hd6_def_case_collision.typ")
t = " ".join(h.text(pdf).split())
sec = t.split("определениями.")[-1]

upper_present = "ОЗУ — Оперативное Запоминающее Устройство" in sec
lower_present = "озу — оперативное запоминающее устройство" in sec

c.check("upper_form_present", upper_present,
        f"вариант с прописными не найден в разделе:\n{sec}")
c.check("lower_form_present", lower_present,
        f"вариант со строчными не найден в разделе (схлопнут дедупом):\n{sec}")
c.check("both_distinct_kept", upper_present and lower_present,
        "дедуп по lower-ключу удалил одно из двух различных определений "
        "(потеря данных)")
c.done()
