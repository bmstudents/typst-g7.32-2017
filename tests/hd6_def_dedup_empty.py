"""hd6: корректный дедуп идентичного термина + пустой раздел.

Часть A — дедуп: термин «Токен …» использован трижды (в т.ч. ПОСЛЕ
раздела). В разделе он должен встречаться РОВНО один раз (схлопывание
повторов по полному ключу — штатное поведение), и при этом запись
обязана появиться, хотя одно из вхождений идёт после раздела (query
у пакета глобальный).

Часть B — отдельный документ без единого определения: раздел всё равно
печатает заголовок и вводное предложение, но НИ одной строки-термина.
"""
import re
import helpers as h

c = h.Checks("hd6_def_dedup_empty")

# --- A: дедуп идентичного термина -----------------------------------------
pdf = h.compile("hd6_def_dedup_empty.typ")
t = " ".join(h.text(pdf).split())
sec = t.split("определениями.")[-1]

c.check("token_present", "Токен — наименьшая единица языка" in sec,
        f"термин не попал в раздел:\n{sec}")
c.check("token_dedup_once", sec.count("Токен — наименьшая единица языка") == 1,
        f"термин повторён в разделе {sec.count('Токен — наименьшая единица языка')} раз, ожидался 1\n{sec}")

# --- B: раздел без определений (отдельный .typ компилируем налету) ---------
import os
empty_typ = os.path.join(h.TESTS_DIR, "hd6_def_empty_section.typ")
with open(empty_typ, "w", encoding="utf-8") as f:
    f.write(
        '#import "../gost732-2017/g7.32-2017.typ": *\n'
        '#show: гост732-2017\n\n'
        '= Раздел\n'
        'Определений в документе нет.\n\n'
        '#определения_обозначения_сокращения_раздел()\n'
    )
pdf2 = h.compile("hd6_def_empty_section.typ")
t2 = " ".join(h.text(pdf2).split())

c.check("empty_has_heading", "ОПРЕДЕЛЕНИЯ, ОБОЗНАЧЕНИЯ И СОКРАЩЕНИЯ" in t2,
        f"нет заголовка раздела в пустом случае:\n{t2}")
c.check("empty_has_intro", "применяют следующие термины" in t2,
        "нет вводного предложения в пустом разделе")
# После вводного предложения и до футера-номера не должно остаться терминов
# с тире-определением. Грубая эвристика: нет «— » в хвосте раздела.
tail = t2.split("определениями.")[-1].strip()
# хвост может содержать только номер страницы
c.check("empty_no_term_lines", re.search(r"—", tail) is None,
        f"в пустом разделе неожиданно появились строки-термины: '{tail}'")
c.done()
