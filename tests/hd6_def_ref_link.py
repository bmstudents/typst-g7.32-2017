"""hd6: текст-ссылка определения + @-ссылка резолвится без поломки.

definition(ref_text, text): когда раздел уже отрендерен (а query
глобальный — значит всегда, если раздел в документе есть), КАЖДОЕ
вхождение печатает ref_text как кликабельную ссылку на запись раздела.
Метка строится как prefix + lower(полный_текст) + "-0" — то есть
содержит пробелы, тире и кириллицу. Проверяем, что:

  * ref_text «кэш-память» выводится дословно в обоих местах (до и после
    раздела), а не заменяется на номер/пустоту/полный текст определения;
  * компиляция не падает и не выдаёт битых ссылок (compile бросил бы);
  * обычная @-ссылка на подраздел резолвится в его номер «2.1»
    (sanity: механизм ref в пакете не сломан определениями).
"""
import re
import helpers as h

c = h.Checks("hd6_def_ref_link")
pdf = h.compile("hd6_def_ref_link.typ")
t = " ".join(h.text(pdf).split())

# ref_text до раздела.
m1 = re.search(r"маркерА\s+(.+?)\s+маркерБ", t)
v1 = m1.group(1) if m1 else ""
c.check("ref_text_before_section", v1 == "кэш-память",
        f"текст-ссылка до раздела = '{v1}', ожидалось 'кэш-память'")

# ref_text после раздела.
m2 = re.search(r"маркерВ\s+(.+?)\s+маркерГ", t)
v2 = m2.group(1) if m2 else ""
c.check("ref_text_after_section", v2 == "кэш-память",
        f"текст-ссылка после раздела = '{v2}', ожидалось 'кэш-память'")

# Запись термина в разделе ровно одна (повтор схлопнут).
sec = t.split("определениями.")[-1]
c.check("entry_once", sec.count("Кэш — буфер быстрого доступа") == 1,
        f"термин в разделе встречается {sec.count('Кэш — буфер быстрого доступа')} раз, ожидался 1")

# @-ссылка на подраздел -> его номер вида «N.M». Само значение N зависит от
# нумерации заголовков (раздел определений в счётчике не участвует), поэтому
# инвариант проверяем по ФОРМЕ: ссылка должна резолвиться в номер «цифра.цифра»,
# совпадающий с номером, напечатанным у самого подраздела.
m3 = re.search(r"маркерД\s+(.+?)\s+маркерЕ", t)
v3 = m3.group(1) if m3 else ""
c.check("section_ref_is_subsection_number", re.fullmatch(r"\d+\.\d+", v3) is not None,
        f"@-ссылка на подраздел = '{v3}', ожидался номер вида 'N.M'")
# Тот же номер должен стоять перед заголовком подраздела.
c.check("section_ref_matches_heading", f"{v3} Целевой подраздел" in t,
        f"номер ссылки '{v3}' не совпал с номером у заголовка подраздела:\n{t}")
c.done()
