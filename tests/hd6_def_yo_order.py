"""hd6: алфавитный порядок терминов в разделе определений.

Инвариант (русский алфавит, ГОСТ 7.32-2017 п.3): термины раздела
«ОПРЕДЕЛЕНИЯ, ОБОЗНАЧЕНИЯ И СОКРАЩЕНИЯ» идут строго по алфавиту.
Буква Ё в русском алфавите стоит между Е и Ж, то есть ожидаемый
порядок начал терминов:

    Адрес, Единица, Ёлка, Ёмкость, Жёсткость, Яблоко

Пакет сортирует ключи через .sorted() по кодпойнтам Unicode, где
ё = U+0451 идёт ПОСЛЕ я = U+044F. Поэтому «Ёлка»/«Ёмкость»
ошибочно уезжают в самый конец, после «Яблоко» — нарушение алфавита.
"""
import helpers as h

c = h.Checks("hd6_def_yo_order")
pdf = h.compile("hd6_def_yo_order.typ")
t = " ".join(h.text(pdf).split())

# Отрезаем интро-предложение, дальше — только список терминов.
sec = t.split("определениями.")[-1]

terms = ["Адрес", "Единица", "Ёлка", "Ёмкость", "Жёсткость", "Яблоко"]
positions = {term: sec.find(term) for term in terms}

c.check("all_present", all(p >= 0 for p in positions.values()),
        f"не все термины в разделе: {positions}")

expected = ["Адрес", "Единица", "Ёлка", "Ёмкость", "Жёсткость", "Яблоко"]
actual = sorted(terms, key=lambda w: positions[w])
c.check("russian_alphabetical_order", actual == expected,
        f"порядок в разделе {actual}, ожидался русский алфавит {expected}\n"
        f"(буква Ё должна стоять между Е и Ж, а не после Я)\nраздел: {sec}")

# Точечно: «Ёлка» должна идти РАНЬШЕ «Жёсткость» и РАНЬШЕ «Яблоко».
c.check("yo_before_zhe", 0 <= positions["Ёлка"] < positions["Жёсткость"],
        f"«Ёлка» (поз {positions['Ёлка']}) не раньше «Жёсткость» (поз {positions['Жёсткость']})")
c.check("yo_before_ya", 0 <= positions["Ёмкость"] < positions["Яблоко"],
        f"«Ёмкость» (поз {positions['Ёмкость']}) не раньше «Яблоко» (поз {positions['Яблоко']})")
c.done()
