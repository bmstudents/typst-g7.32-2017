"""he1 #1 — ГЛАВНЫЙ БАГ: при фиче подпись листинга НАЕЗЖАЕТ на рамку тела.

Тело листинга в пакете оборачивается в table() с видимой рамкой
(styles/raw.typ). Подпись «Листинг N – ...» стоит сверху. Без фичи между
нижней кромкой инка подписи и ВЕРХНЕЙ ГРАНИЦЕЙ РАМКИ тела есть зазор ~6.7pt.

С фичей `да` строка figure.typ:75 добавляет v(-0.5em) ПОСЛЕ подписи —
рамка тела поднимается на ~7pt и наезжает на подпись: в растре две полосы
инка (подпись и рамка) СЛИВАЮТСЯ в одну. Это и есть наезд.

Хитрость: проверка по словам pdftotext этого НЕ ловит — между словом
подписи и первым словом тела «ИНКТЕСТ» остаётся +6.48pt (слово тела ниже
рамки на величину inset 10pt). Наезжает именно РАМКА, а её видно только в
растре. Поэтому тест растровый.

ИНВАРИАНТ:
  без фичи — подпись и рамка тела суть РАЗНЫЕ полосы инка, зазор > 2pt;
  с фичей — они обязаны оставаться РАЗНЫМИ полосами с зазором > 0.
  Если с фичей полосы слиплись (зазор <= 0) — FAIL: наезд.
  Файл пакета: gost732-2017/styles/figure.typ, строка 75 (v(-0.5em) после
  подписи листинга при feature-table-small-spacing).
"""
import he1_ink as ink
import helpers as h

c = h.Checks("he1_listing_caption_ink")

# окно по y: ниже заголовка «Раздел» (~68pt) и выше тела/конца страницы.
# окно по x: основная колонка (исключаем номер страницы по центру вверху —
# он и так выше y_lo). Берём весь лист по x, отсекаем по y.
Y_LO, Y_HI = 72.0, 200.0


def caption_to_body_gap(typ):
    png, ppi = ink.render_png(typ)
    bands = ink.ink_bands(png, ppi, y_lo_pt=Y_LO, y_hi_pt=Y_HI)
    # band[0] — подпись «Листинг ...», band[1] — тело листинга (рамка+код)
    return bands, png, ppi


b_no, _, _ = caption_to_body_gap("he1_listing_caption_ink_noflag.typ")
b_fl, png_fl, ppi_fl = caption_to_body_gap("he1_listing_caption_ink_flag.typ")

# 1) sanity без фичи: подпись и тело — две отдельные полосы с явным зазором
ok_no = len(b_no) >= 2
gap_no = (b_no[1][0] - b_no[0][1]) if ok_no else -1
c.check("noflag_two_bands_with_gap", ok_no and gap_no > 2,
        f"без фичи ожидались 2 полосы инка с зазором>2pt; "
        f"полосы={[(round(a,1),round(b,1)) for a,b in b_no]} зазор={gap_no:.2f}")

# 2) то же расположение блоков должно сохраниться С фичей: минимум 2 полосы,
#    подпись и тело НЕ слипаются. Если фича схлопнула их в одну полосу — наезд.
two_bands_fl = len(b_fl) >= 2
gap_fl = (b_fl[1][0] - b_fl[0][1]) if two_bands_fl else -999
c.check("flag_no_overlap", two_bands_fl and gap_fl > 0,
        f"НАЕЗД подписи листинга на рамку тела при фиче "
        f"`фича-маленький-отступ-вокруг-таблиц: да`: "
        f"полос инка={len(b_fl)} ({[(round(a,1),round(b,1)) for a,b in b_fl]}), "
        f"зазор подпись→тело={gap_fl:.2f}pt (ожидался > 0). "
        f"v(-0.5em) в figure.typ:75 поднял рамку тела на ~7pt при базовом "
        f"зазоре ~{gap_no:.1f}pt и схлопнул их. PNG: {png_fl}")

# 3) фича может уменьшать зазор, но не делать его меньше, чем «впритык».
#    отдельная мягкая проверка читаемости (не критичная для overlap).
c.check("flag_gap_readable", two_bands_fl and gap_fl > 2,
        f"зазор подпись→рамка тела при фиче = {gap_fl:.2f}pt — практически "
        f"впритык/наезд (без фичи было {gap_no:.2f}pt). figure.typ:75")

c.done()
