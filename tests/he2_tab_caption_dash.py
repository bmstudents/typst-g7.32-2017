"""he2 EDGE-таблицы #10: РАЗДЕЛИТЕЛЬ в подписи таблицы должен быть ТИРЕ (—).

ГОСТ 7.32-2017 и русская типографика: наименование таблицы оформляется как
«Таблица N — Наименование», где разделитель — ДЛИННОЕ ТИРЕ (em-dash, U+2014).

В пакете разделитель задан как `set figure.caption(separator: [ -- ])`
(gost732-2017/styles/figure.typ:107). В Typst markup `--` обрабатывается
smartquote-механизмом и превращается в КОРОТКОЕ тире / en-dash (U+2013),
а НЕ в длинное тире (U+2014). То есть на выходе получается «Таблица 1 – ...»
вместо требуемого «Таблица 1 — ...».

ИНВАРИАНТ (строгий, по ГОСТ):
  разделитель между номером и наименованием == U+2014 (—), а не U+2013 (–).

Если этот тест FAIL с char=U+2013 — это и есть баг разделителя:
  Файл: gost732-2017/styles/figure.typ, строка `separator: [ -- ]`
  Фикс: заменить на `separator: [ — ]` (буквальное длинное тире U+2014).
"""
import re
import helpers as h

c = h.Checks("he2_tab_caption_dash")
pdf = h.compile("he2_tab_caption_dash.typ")
t = h.text(pdf)

# вытащить символ-разделитель между «Таблица 1» и «Наименование»
m = re.search(r"Таблица\s+1\s+(\S)\s+Наименование", t)
c.check("caption_line_present", m is not None,
        f"строка подписи 'Таблица 1 <sep> Наименование' не найдена:\n{t!r}")

if m:
    sep = m.group(1)
    EM, EN = "—", "–"
    c.check("separator_is_em_dash", sep == EM,
            f"разделитель подписи таблицы = {sep!r} (U+{ord(sep):04X}), "
            f"ожидалось длинное тире '—' (U+2014) по ГОСТ 7.32-2017. "
            f"Получено короткое тире '–' (U+2013): smartquote сжал `--` в figure.typ. "
            f"Файл: gost732-2017/styles/figure.typ, `separator: [ -- ]`.")
c.done()
