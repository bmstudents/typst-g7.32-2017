"""he2 EDGE-таблицы #3: УЗКАЯ колонка (3cm) + длинный многословный текст.

Левая колонка фиксированной ширины 3cm = 85.04pt; её левый край = левое поле
полосы (85.04pt), значит правая граница колонки ≈ 170.1pt. Содержимое внутри
inset 10pt с каждой стороны → область текста 95.04..160.04pt.

Текст — много КОРОТКИХ русских слов (мяч, кот, ...), каждое из которых заведомо
помещается в колонку. Поэтому неизбежного Typst-переполнения неразрывным токеном
здесь нет: любое слово, вылезшее за правую границу колонки, означает дефект
геометрии (обёртка таблицы в figure.typ ужала колонку, либо h(-1.25cm) сбил
ширины), а не «слово не влезло».

ИНВАРИАНТЫ:
  1) текст реально перенёсся на >=3 строки (короткие слова заполняют узкую
     колонку построчно);
  2) ни одно слово левой колонки не выходит правее правой ГРАНИЦЫ колонки
     (170.1pt + допуск). Слова правой колонки исключаем (x0 заметно правее).

Файл пакета при провале: gost732-2017/styles/figure.typ (обёртка table
columns:(1fr) + h(-1.25cm)) / styles/table.typ.
"""
import helpers as h

c = h.Checks("he2_tab_narrow_wrap")
pdf = h.compile("he2_tab_narrow_wrap.typ")
ws = h.words(pdf)

LEFT = 30 / 25.4 * 72.0           # 85.04
COL_W = 3 * 10 / 25.4 * 72.0      # 3cm = 85.04
COL_RIGHT = LEFT + COL_W          # ≈ 170.08
TOL = 2.0

# слова левой колонки = короткие слова содержимого на стр.1 в области тела (y<400),
# x0 в пределах области текста колонки (< COL_RIGHT)
content = {"мяч", "кот", "дом", "сыр", "луг", "бор", "код", "ряд", "ток", "рот",
           "шов", "лес", "мёд", "бук", "ель", "дуб", "над", "низ", "око", "очи", "усы"}
left_words = [w for w in ws if w[0] == 1 and w[5] in content and w[2] < 400 and w[1] < COL_RIGHT]

rows = sorted(set(round(w[4]) for w in left_words))
c.check("multiline_wrap", len(rows) >= 3,
        f"узкая колонка заняла {len(rows)} строк (<3) — перенос не сработал: {rows}. "
        f"Файл: gost732-2017/styles/table.typ")

offenders = [(round(w[3], 1), w[5]) for w in left_words if w[3] > COL_RIGHT + TOL]
c.check("within_column_right_border", not offenders,
        f"короткие слова узкой колонки вылезли за её правую границу {COL_RIGHT:.1f}pt: "
        f"нарушители={offenders} — колонка ужата геометрией обёртки. "
        f"Файл: gost732-2017/styles/figure.typ")
c.done()
