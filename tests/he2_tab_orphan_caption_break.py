"""he2 EDGE-таблицы #11 (НАЙДЕННЫЙ БАГ): ложное «Продолжение таблицы» и сирота-
подпись у одно-строчной НЕразрывной таблицы у нижнего края страницы.

СЦЕНАРИЙ: заполнитель v(650pt) прижимает короткую таблицу (1 колонка, 1 строка)
к низу страницы. На странице помещается только ПОДПИСЬ; единственная строка тела
перетекает на следующую страницу.

НАБЛЮДАЕМЫЙ ДЕФЕКТ (gost732-2017/styles/figure.typ):
  Стр.1:  «Таблица 1 – Короткая неразрывная таблица»  (подпись-сирота, без тела)
  Стр.2:  «Продолжение таблицы 1»  +  «ЕДИНСТВЕННАЯСТРОКА»

Причина: подпись таблицы реализована как table.header внутри таблицы-обёртки
(figure.typ). Когда обёртка переносится через границу страницы, header
повторяется на новой странице, а счётчик continuation уже == 1 → печатается
«Продолжение таблицы N». При этом таблица из одной строки ФАКТИЧЕСКИ не
разрывалась — её просто оторвали от осиротевшей подписи.

ИНВАРИАНТЫ (по ГОСТ: целая таблица не разрывается, подпись не сирота):
  1) НЕ должно быть текста «Продолжение» — таблица из одной строки не
     разрывается, значит и продолжения у неё нет;
  2) подпись «Таблица 1» и тело «ЕДИНСТВЕННАЯСТРОКА» должны быть на ОДНОЙ
     странице (подпись не оторвана от тела).

Файл пакета: gost732-2017/styles/figure.typ — caption как table.header в
breakable-обёртке; нет привязки «подпись+тело» как неразрывного блока (для
рисунков это сделано через block(breakable:false), для таблиц — нет).
"""
import helpers as h

c = h.Checks("he2_tab_orphan_caption_break")
pdf = h.compile("he2_tab_orphan_caption_break.typ")
t = h.text(pdf)
ws = h.words(pdf)

c.check("no_false_continuation", "Продолжение" not in t,
        f"одно-строчная неразрывная таблица породила 'Продолжение таблицы' — "
        f"ложный разрыв целой таблицы. Файл: gost732-2017/styles/figure.typ:\n{t!r}")

pg_cap = next((w[0] for w in ws if w[5] == "Таблица"), None)
pg_body = next((w[0] for w in ws if w[5] == "ЕДИНСТВЕННАЯСТРОКА"), None)
c.check("caption_with_body", pg_cap is not None and pg_body is not None and pg_cap == pg_body,
        f"подпись (стр.{pg_cap}) оторвана от тела (стр.{pg_body}) — подпись-сирота. "
        f"Целая таблица должна целиком уйти на следующую страницу вместе с подписью. "
        f"Файл: gost732-2017/styles/figure.typ")
c.done()
