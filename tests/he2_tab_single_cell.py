"""he2 EDGE-таблицы #1: таблица из ОДНОЙ ячейки.

ИНВАРИАНТЫ:
  1) подпись «Таблица 1» присутствует, и слово «Таблица» встречается ровно ОДИН
     раз (нет ложного «Продолжение таблицы» для не-разрывной таблицы);
  2) содержимое единственной ячейки 'ЕДИНСТВЕННАЯ' отрендерилось;
  3) левый край подписи («Таблица») == левому полю полосы (30мм = 85pt), т.е.
     подпись прижата влево, а не центрирована и не уехала в поле.
  4) левая граница тела (левый край содержимого ячейки) НЕ левее левого поля —
     т.е. h(-1.25cm) в теле не выталкивает таблицу в левое поле.

Файл пакета при провале: gost732-2017/styles/figure.typ (логика continuation /
сдвига h(-1.25cm)).
"""
import helpers as h

c = h.Checks("he2_tab_single_cell")
pdf = h.compile("he2_tab_single_cell.typ")
t = h.text(pdf)
ws = h.words(pdf)

LEFT = 30 / 25.4 * 72.0  # 85.04
TOL = 1.5

c.check("supplement_number", "Таблица 1" in t, f"нет 'Таблица 1':\n{t}")
c.check("cell_content", "ЕДИНСТВЕННАЯ" in t, f"нет содержимого ячейки:\n{t}")

# нет ложного «Продолжение»
c.check("no_false_continuation", "Продолжение" not in t,
        f"появилось ложное 'Продолжение таблицы' для не-разрывной 1-ячеечной таблицы:\n{t}")

# «Таблица» встречается один раз (это слово supplement; в подписи 'Одна ячейка'
# слова 'Таблица' нет)
n_tab = t.count("Таблица")
c.check("supplement_once", n_tab == 1,
        f"слово 'Таблица' встречается {n_tab} раз (ожидали 1) — дублируется header:\n{t}")

cap_x = [w[1] for w in ws if w[5] == "Таблица"]
c.check("caption_left_aligned", cap_x and abs(cap_x[0] - LEFT) <= TOL,
        f"левый край подписи x0={cap_x} != левому полю {LEFT:.1f}pt (±{TOL}). "
        f"Файл: gost732-2017/styles/figure.typ")

body_x = [w[1] for w in ws if w[5] == "ЕДИНСТВЕННАЯ"]
c.check("body_not_in_margin", body_x and body_x[0] >= LEFT - TOL,
        f"содержимое тела x0={body_x} левее левого поля {LEFT:.1f}pt — "
        f"h(-1.25cm) вытолкнул таблицу в поле. Файл: gost732-2017/styles/figure.typ")
c.done()
