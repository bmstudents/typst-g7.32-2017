"""he3_appendix_listov_not_last: «Листов N» на титуле приложения, которое
НЕ является последним в документе.

Семантика «Листов N» задана существующими тестами g8_appendix_sheets и
pj_app_sheets: N == число СТРАНИЦ КОНТЕНТА приложения (без титульной
страницы «ПРИЛОЖЕНИЕ X»). Там приложение из 2 страниц контента → «Листов 2».

Здесь два приложения подряд, у каждого РОВНО ОДНА страница контента.
Футеры подтверждают это: собственная нумерация каждого приложения
рестартует и на странице контента показывает «1». Значит на титуле
каждого приложения должно стоять «Листов 1».

НАЙДЕННЫЙ БАГ (gost732-2017/utils/appendix.typ): для приложения, которое
не последнее, метка <internal-appendix-end{letter}> прикреплена к
завершающему `#metadata("kostyl") #label(end)` ПОСЛЕ `pagebreak(weak:true)`.
Этот нулевой по высоте маркер не «якорится» на собственной странице
приложения, а протекает через слабые разрывы и setup следующего приложения
до ПОСЛЕДНЕЙ физической страницы документа. В итоге
counter(page).at(label(endА)) == final, поэтому:
  1) разность endА-beginА завышена (берётся до конца документа);
  2) поправка `minus = -1*int(end != final)` не срабатывает (end==final),
     хотя приложение не последнее.
Результат: «Листов» первого приложения многократно завышен (здесь 3
вместо 1). Последнее приложение считается верно, т.к. для него end==final
действительно корректно. Одиночное приложение (всегда последнее) тоже
верно — поэтому g8/pj не ловят баг."""
import re
import helpers as h

c = h.Checks("he3_appendix_listov_not_last")
pdf = h.compile("he3_appendix_listov_not_last.typ")
ws = h.words(pdf)
t = " ".join(h.text(pdf).split())

# Обе титульные страницы есть.
c.check("two_appendix_titles",
        t.count("ПРИЛОЖЕНИЕ") >= 2,
        f"ожидали два титула приложений, текст: {t[:160]}")

# Из футеров: у каждого приложения ровно одна страница контента (footer==1
# у страницы контента, следующая страница — уже титул след. приложения или
# конец). Соберём физические страницы и их футеры.
footers = {p: h.footer_word(pdf, p) for p in range(1, h.page_count(pdf) + 1)}
# Страницы контента приложений — те, где собственная нумерация == "1" и
# первое слово начинается с «Контент».
content_pages = [p for p in footers
                 if footers[p] == "1"
                 and (h.first_word(pdf, p) or (0, ""))[1] == "Контент"]
c.check("each_appendix_one_content_page",
        len(content_pages) == 2,
        f"ожидали по 1 странице контента в каждом приложении (2 всего), "
        f"нашли {content_pages} (footers={footers})")

# Значения «Листов N» в порядке появления.
listov = [int(x) for x in re.findall(r"Листов\s*([0-9]+)", t)]
c.check("two_listov_values",
        len(listov) == 2,
        f"ожидали два значения 'Листов', нашли {listov}")

# ИНВАРИАНТ (ловит баг): у каждого приложения по 1 странице контента →
# оба значения «Листов» должны быть 1. Падает на первом (не последнем).
if len(listov) == 2:
    c.check("listov_first_appendix_correct",
            listov[0] == 1,
            f"первое (не последнее) приложение: 'Листов {listov[0]}', "
            f"ожидали 'Листов 1' (1 страница контента). БАГ в "
            f"utils/appendix.typ: метка end утекает на последнюю страницу "
            f"документа, разность завышена и поправка minus не применяется.")
    c.check("listov_last_appendix_correct",
            listov[1] == 1,
            f"последнее приложение: 'Листов {listov[1]}', ожидали 'Листов 1'")

c.done()
