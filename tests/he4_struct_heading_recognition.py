"""he4: НАЙДЕННЫЙ БАГ. Структурный элемент «Перечень сокращений и ссылок»
(#перечень_сокращений_и_ссылок из пакета) НЕ распознаётся как
структурный заголовок и оформляется как обычный нумерованный раздел.

Корень бага:
  gost732-2017/utils/heading.typ:25  определяет текст заголовка
      "= Перечень сокращений и ссылок"
  gost732-2017/internal-utils/utils.typ:22 и :32  в регэкспах
      should_be_unnumbered_heading / should_be_upper_heading ожидают
      "перечень сокращений и обозначений"
  Слово "ссылок" (в заголовке) != "обозначений" (в регэкспе) -> регэксп
  не срабатывает -> заголовок считается обычным разделом.

Последствия (всё проверяется ниже):
  1. заголовок печатается как "1 Перечень ..." (нумеруется);
  2. оформляется строчными и прижат влево (а не ПРОПИСНЫМИ по центру,
     как ВВЕДЕНИЕ/ЗАКЛЮЧЕНИЕ);
  3. сбивает сквозную нумерацию разделов: первый реальный раздел
     получает номер 2 вместо 1.

Тест строгий: при исправлении пакета (синхронизация регэкспа с текстом
заголовка, либо текста заголовка с регэкспом) он начнёт проходить.
"""
import re
import helpers as h

c = h.Checks("he4_struct_heading_recognition")
pdf = h.compile("he4_struct_heading_recognition.typ")
ws = h.words(pdf)
t = " ".join(h.text(pdf).split())

# Контроль: «Перечень сокращений и ссылок» вообще отрендерен.
c.check("heading_present", "Перечень сокращений и ссылок" in t or "ПЕРЕЧЕНЬ" in t,
        f"структурный заголовок не отрендерен: {t[:200]}")

# --- (1) НЕ должен быть пронумерован ---
# Если бы он был структурным, в тексте не было бы "1 Перечень".
numbered = bool(re.search(r"\b1\s+Перечень сокращений и ссылок", t))
c.check("struct_heading_not_numbered", not numbered,
        "БАГ: 'Перечень сокращений и ссылок' пронумерован как раздел "
        "('1 Перечень ...'). Должен быть структурным (без номера). "
        "Причина: heading.typ:25 'ссылок' != internal-utils/utils.typ:22 "
        "'обозначений'.")

# --- (2) сквозная нумерация разделов не должна сбиваться ---
# Первый реальный нумерованный раздел обязан быть «1 Аналитический раздел».
c.check("first_section_is_1", "1 Аналитический раздел" in t,
        "БАГ: первый раздел не получил номер 1.")
c.check("second_section_is_2", "2 Конструкторский раздел" in t,
        "БАГ: второй раздел не получил номер 2.")
# и НЕ должно быть сдвига на 2/3
shifted = "2 Аналитический раздел" in t or "3 Конструкторский раздел" in t
c.check("no_numbering_shift", not shifted,
        "БАГ: нумерация разделов сдвинута (перечень сокращений съел номер 1). "
        "Реальный первый раздел стал '2 Аналитический раздел'.")

# --- (3) оформление: ПРОПИСНЫМИ по центру, как ВВЕДЕНИЕ/ЗАКЛЮЧЕНИЕ ---
# Геометрия страницы A4: ширина 595pt, поля 30мм/15мм -> центр полосы ~308.
# Структурный заголовок центрируется; обычный — прижат влево (x0 ~ 85..131).
per_words = [w for w in ws if w[5] in ("Перечень", "ПЕРЕЧЕНЬ")]
c.check("struct_heading_word_found", len(per_words) >= 1,
        "не нашли слово 'Перечень'/'ПЕРЕЧЕНЬ' с координатами")
if per_words:
    x0 = per_words[0][1]
    # центрированный заголовок начинается заметно правее левого поля.
    c.check("struct_heading_centered", x0 > 180,
            f"БАГ: заголовок прижат влево (x0={x0:.1f}), а структурный "
            f"элемент должен центрироваться (как ВВЕДЕНИЕ).")
    # ПРОПИСНЫЕ: текст должен содержать 'ПЕРЕЧЕНЬ', а не 'Перечень'.
    c.check("struct_heading_upper", "ПЕРЕЧЕНЬ СОКРАЩЕНИЙ" in t,
            "БАГ: заголовок не прописными (нет 'ПЕРЕЧЕНЬ СОКРАЩЕНИЙ'); "
            "структурные элементы оформляются ПРОПИСНЫМИ.")

c.done()
