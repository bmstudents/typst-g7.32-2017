"""he4: два приложения А и Б с рисунками И таблицами.
Инварианты: основной раздел -> Рисунок 1 / Таблица 1 (числовые);
приложение А -> А.1/А.2; приложение Б -> Б.1/Б.2 (счётчики сброшены
между приложениями); рисунки и таблицы внутри приложения нумеруются
независимо.
"""
import re
import helpers as h

c = h.Checks("he4_two_appendices")
pdf = h.compile("he4_two_appendices.typ")
t = " ".join(h.text(pdf).split())

c.check("appendix_titles", "ПРИЛОЖЕНИЕ А" in t and "ПРИЛОЖЕНИЕ Б" in t,
        "нет заголовков обоих приложений")

# основной раздел: числовая нумерация
c.check("main_fig_numeric", "Рисунок 1 – Основная схема" in t,
        "основной рисунок не пронумерован числом 1")
c.check("main_tab_numeric", "Таблица 1 – Основная таблица" in t,
        "основная таблица не пронумерована числом 1")

# приложение А: А.1 (рис), А.2 (рис), Таблица А.1
c.check("appA_fig1", "Рисунок А.1 – Схема А первая" in t, "нет Рисунок А.1")
c.check("appA_fig2", "Рисунок А.2 – Схема А вторая" in t, "нет Рисунок А.2 (счётчик рис в А не дошёл до 2)")
c.check("appA_tab1", "Таблица А.1 – Таблица А первая" in t,
        "нет Таблица А.1 (счётчик таблиц в А должен начинаться с 1, независимо от рисунков)")

# приложение Б: счётчики сброшены -> Б.1/Б.2 для таблиц, Б.1 для рис
c.check("appB_tab1", "Таблица Б.1 – Таблица Б первая" in t,
        "нет Таблица Б.1 (счётчик таблиц не сброшен на входе в Б)")
c.check("appB_fig1", "Рисунок Б.1 – Схема Б первая" in t,
        "нет Рисунок Б.1 (счётчик рисунков не сброшен на входе в Б)")
c.check("appB_tab2", "Таблица Б.2 – Таблица Б вторая" in t,
        "нет Таблица Б.2")

# негатив: в Б не должно быть А.x; в основном не должно быть А./Б.
c.check("no_leak_A_into_B",
        "Рисунок А.3" not in t and "Таблица А.2" not in t,
        "счётчики приложения А протекли (A.3 / A.2 не ожидаются)")

c.done()
