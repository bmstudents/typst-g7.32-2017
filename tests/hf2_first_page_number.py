"""hf2: фактическое поведение нумерации ПЕРВОЙ страницы.

style_page (gost732-2017/styles/page.typ:6-17) ставит footer =
counter(page).display("1") БЕЗ какого-либо подавления на первой странице.
Поэтому голый документ (без вставленного титула) печатает «1» на самой
первой физической странице.

По ГОСТ 7.32 титульный лист в нумерацию ВХОДИТ (это стр.1), но номер на нём
НЕ печатается. Голый шаблон титула не делает, поэтому стр.1 = видимый «1».
Здесь мы ФИКСИРУЕМ это фактическое поведение строгим инвариантом — если оно
изменится (например пакет начнёт прятать номер на стр.1 или печатать «2»),
тест упадёт и заставит пересмотреть поведение.
"""
import helpers as h

c = h.Checks("hf2_first_page_number")
pdf = h.compile("hf2_first_page_number.typ")

f1 = h.footer_word(pdf, 1)
f2 = h.footer_word(pdf, 2)

# Факт: на первой странице печатается видимый арабский номер.
c.check("page1_has_visible_number",
        f1 is not None and f1.isdigit(),
        f"на стр.1 нет видимого числового футера: {f1!r}")

# И этот номер — именно «1» (счёт начинается с первой физической страницы).
c.check("page1_is_one",
        f1 == "1",
        f"футер стр.1 = {f1!r}, ждём '1' (фактическое поведение пакета)")

# Вторая страница — «2» (счёт идёт со стр.1, без пропусков).
c.check("page2_is_two",
        f2 == "2",
        f"футер стр.2 = {f2!r}, ждём '2'")

# Номер стр.1 НЕ окрашен в белый (в голом документе он реально виден, а не
# спрятан как титул). Проверяем косвенно: pdftotext извлёк его в текст. слой.
txt = h.text(pdf)
c.check("page1_number_in_textlayer",
        "1" in txt,
        "номер стр.1 не попал в текстовый слой")

c.done()
