"""hf2: БАГ — титульный лист вне сквозной нумерации ломает номера тела.

Файл пакета: gost732-2017/utils/insert.typ:48-50

    if not в-нумерации {
        counter(page).update(n => calc.max(n - 1, 1))
    }

Замысел (по комментариям в insert.typ): лист с `в-нумерации: false` не
увеличивает счётчик страниц — типичный ГОСТ-приём для титула/задания, которые
печатаются вне сквозной нумерации. Декремент возвращает «занятый» листом номер.

БАГ: clamp `calc.max(n - 1, 1)` не даёт счётчику опуститься ниже 1. Когда
такой лист стоит ПЕРВЫМ (n=1 → max(0,1)=1), декремент НЕ срабатывает, и
следующая страница тела снова получает «1». Документ получает ДВА номера «1».

Сценарий теста (титул не-в-нумерации + 3 страницы тела) даёт футеры:
    стр.1 (титул, номер белый) = «1»
    стр.2 (тело)              = «1»   ← ДУБЛЬ
    стр.3 (тело)              = «2»
    стр.4 (тело)              = «3»

Инвариант: видимые номера страниц во всём документе должны быть строго
уникальны и монотонны. Дубль «1» обязан валить тест.
"""
import helpers as h

c = h.Checks("hf2_titlepage_offbyone")
pdf = h.compile("hf2_titlepage_offbyone.typ")

n = h.page_count(pdf)
c.check("four_pages", n == 4, f"страниц {n}, ждём 4 (титул + 3 тела)")

# Номер в нижнем поле каждой страницы (текстовый слой; белый номер титула
# тоже извлекается pdftotext — TestVkr его «видит»).
footers = []
for p in range(1, n + 1):
    nums = [w for w in h.words(pdf) if w[0] == p and w[2] > 700 and w[5].isdigit()]
    footers.append(nums[0][5] if nums else None)

# ИНВАРИАНТ 1: номера страниц уникальны во всём документе (нет двух «1»).
non_none = [f for f in footers if f is not None]
c.check("page_numbers_unique",
        len(non_none) == len(set(non_none)),
        f"номера страниц дублируются: {footers} "
        f"(insert.typ:49 calc.max(n-1,1) floor — титул вне нумерации не "
        f"декрементировал счётчик, тело начинается с повторного '1')")

# ИНВАРИАНТ 2: первая СТРАНИЦА ТЕЛА (стр.2) не должна повторять номер титула.
c.check("body_does_not_repeat_title_number",
        footers[1] != footers[0],
        f"стр.2 (тело) повторяет номер титула: title={footers[0]!r} "
        f"body1={footers[1]!r}")

# ИНВАРИАНТ 3: видимая нумерация тела монотонно возрастает без повторов первого
# значения. Берём номера тела (стр.2..4) — они должны строго возрастать.
body = footers[1:]
strictly_inc = all(
    body[i] is not None and body[i + 1] is not None
    and int(body[i + 1]) > int(body[i])
    for i in range(len(body) - 1)
)
c.check("body_strictly_increasing",
        strictly_inc,
        f"номера тела не строго возрастают: {body}")

c.done()
