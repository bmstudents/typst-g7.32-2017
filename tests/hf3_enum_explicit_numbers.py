"""hf3_enum_explicit_numbers: ИНВАРИАНТ — явно заданные номера пунктов
перечисления должны сохраняться.

В Typst запись «5. текст» задаёт ПУНКТ с явным номером 5 (enum item с
number=5). Стандартный enum продолжит 5,6,7. Рукописный show enum в
gost732-2017/styles/list.typ ведёт СВОЙ счётчик `let i = 1` и игнорирует
`phase.number`, поэтому «5. 6. 7.» превращается в «1) 2) 3)».
Это скрытый баг: молчаливая порча номеров в документах, где автор задаёт
номер явно (продолжение списка, ссылки на конкретный пункт).
"""
import helpers as h

c = h.Checks("hf3_enum_explicit_numbers")
pdf = h.compile("hf3_enum_explicit_numbers.typ")
t = h.text(pdf)

# Должны присутствовать маркеры 5) 6) 7) (явные номера сохранены).
c.check("keeps_5", "5)" in t,
        f"БАГ ЯВНОЙ НУМЕРАЦИИ (list.typ, show enum): пункт '5.' не дал маркер '5)'. "
        f"Рукописный счётчик 'let i = 1' игнорирует phase.number. Вывод:\n{t!r}")
c.check("keeps_6", "6)" in t, f"нет '6)' (явный номер потерян):\n{t!r}")
c.check("keeps_7", "7)" in t, f"нет '7)' (явный номер потерян):\n{t!r}")

# И НЕ должно быть ошибочной перенумерации с единицы.
c.check("no_wrong_renumber", not ("1)" in t and "2)" in t and "3)" in t),
        f"перечисление перенумеровано с 1) вместо сохранения 5)6)7):\n{t!r}")

c.done()
