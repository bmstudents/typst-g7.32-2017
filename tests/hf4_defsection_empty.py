"""hf4_defsection_empty: определения_обозначения_сокращения_раздел() без определений.

Когда в документе НЕТ ни одного #определение(...), раздел всё равно должен:
  - скомпилироваться без ошибок,
  - напечатать прописной заголовок 'ОПРЕДЕЛЕНИЯ, ОБОЗНАЧЕНИЯ И СОКРАЩЕНИЯ',
  - напечатать вводную фразу 'В настоящем отчете о НИР применяют следующие
    термины с соответствующими определениями.'
  - НЕ напечатать ни одной записи термина (цикл for пуст).

Источник: gost732-2017/utils/definitions.typ ::
definitions_designations_abbreviations_section().
"""
import helpers as h

c = h.Checks("hf4_defsection_empty")
pdf = h.compile("hf4_defsection_empty.typ")
norm = " ".join(h.text(pdf).split())

c.check(
    "heading_upper",
    "ОПРЕДЕЛЕНИЯ, ОБОЗНАЧЕНИЯ И СОКРАЩЕНИЯ" in norm,
    f"нет прописного заголовка раздела определений:\n  {norm[:200]}",
)
c.check(
    "intro_phrase",
    "применяют следующие термины с соответствующими определениями" in norm,
    f"нет вводной фразы раздела:\n  {norm[:240]}",
)
# Заголовок раздела — структурный, не нумеруется.
fw = h.first_word(pdf, 1)
c.check(
    "heading_not_numbered",
    fw is not None and not fw[1].rstrip(".").isdigit(),
    f"заголовок раздела определений получил номер: первое слово {fw}",
)

c.done()
