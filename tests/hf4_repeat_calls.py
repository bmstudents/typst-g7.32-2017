"""hf4_repeat_calls: повторный вызов одних и тех же функций (легитимный).

Контрольный тест: безопасные повторы НЕ должны ломать документ.
  - #введение дважды -> два прописных 'ВВЕДЕНИЕ', оба без номера;
  - размер(3) дважды -> одно и то же значение (чистая функция);
  - идущая следом '= Раздел' получает номер 1 (структурные повторы не
    сбивают нумерацию основной части).
"""
import helpers as h

c = h.Checks("hf4_repeat_calls")
pdf = h.compile("hf4_repeat_calls.typ")
norm = " ".join(h.text(pdf).split())
seq = " ".join(w[5] for w in h.words(pdf))

c.check(
    "vvedenie_twice",
    norm.count("ВВЕДЕНИЕ") == 2,
    f"#введение дважды дал {norm.count('ВВЕДЕНИЕ')} вхождений 'ВВЕДЕНИЕ' (ждали 2):\n  {norm[:200]}",
)
c.check(
    "razmer_pure",
    "A=39pt B=39pt" in norm,
    f"размер(3) непостоянен при повторе:\n  {norm[:200]}",
)
c.check(
    "section_number_intact",
    "1 Раздел" in seq,
    f"повторные структурные вызовы сбили нумерацию основной части:\n  {seq[:240]}",
)

c.done()
