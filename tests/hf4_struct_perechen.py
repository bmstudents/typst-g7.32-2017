"""hf4_struct_perechen: структурный элемент «Перечень сокращений и ссылок».

По ГОСТ 7.32-2017 заголовки структурных элементов (реферат, введение,
заключение, перечень сокращений и т.д.) пишутся ПРОПИСНЫМИ буквами, по
ЦЕНТРУ и БЕЗ номера раздела — они не входят в нумерацию основной части.

Все прочие структурные заголовки пакета (#реферат #введение #заключение
#термины_и_определения #список_исполнителей) ведут себя именно так
(см. hf4_struct_all). А #перечень_сокращений_и_ссылок — НЕТ.

Инвариант: первое слово отчёта НЕ должно быть цифрой «1», т.е. структурный
заголовок не получает номер раздела, и первая настоящая секция получает
номер 1, а не 2.
"""
import helpers as h

c = h.Checks("hf4_struct_perechen")
pdf = h.compile("hf4_struct_perechen.typ")
norm = " ".join(h.text(pdf).split())

# Заголовок должен быть прописными (как все остальные структурные элементы).
c.check(
    "heading_upper",
    "ПЕРЕЧЕНЬ СОКРАЩЕНИЙ И ССЫЛОК" in norm,
    "заголовок 'Перечень сокращений и ссылок' НЕ переведён в верхний регистр.\n"
    "  Причина: в gost732-2017/internal-utils/utils.typ регэксп\n"
    "  should_be_unnumbered_heading/should_be_upper_heading ожидает\n"
    "  'перечень сокращений и обозначений', а константа в\n"
    "  gost732-2017/utils/heading.typ задаёт 'Перечень сокращений и ССЫЛОК'.\n"
    "  Тексты не совпадают -> заголовок трактуется как обычный раздел.\n"
    f"  Текст PDF: {norm[:160]}",
)

# Структурный заголовок НЕ нумеруется -> он не должен начинаться с номера '1'.
words = [w[5] for w in h.words(pdf)]
# Первое содержательное слово страницы 1.
fw = h.first_word(pdf, 1)
c.check(
    "heading_not_numbered",
    fw is not None and fw[1] != "1" and not fw[1].rstrip(".").isdigit(),
    "структурный заголовок получил номер раздела (первое слово — цифра).\n"
    f"  Первое слово страницы: {fw}\n"
    f"  Текст PDF: {norm[:160]}",
)

# Первая НАСТОЯЩАЯ секция должна иметь номер 1 (а не 2): структурный
# элемент не должен «съедать» первый номер.
# Ищем 'Первый' и убеждаемся, что перед ним стоит '1', а не '2'.
seq = " ".join(words)
c.check(
    "real_section_is_1",
    "1 Первый" in seq,
    "первая настоящая секция получила НЕ номер 1 — структурный элемент\n"
    "  ошибочно занял номер раздела.\n"
    f"  Последовательность слов: {seq[:200]}",
)

c.done()
