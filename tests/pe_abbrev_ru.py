"""pe_abbrev_ru: русский алиас #перечень_сокращений_и_ссылок даёт заголовок 'Перечень сокращений и ссылок'.

ВНИМАНИЕ: текст константы — '...и ссылок', а белый список структурных
заголовков в internal-utils содержит '...и обозначений'. Поэтому этот
заголовок НЕ распознаётся как структурный и рендерится в исходном
регистре (mixed-case) с номером, в отличие от прочих структурных
элементов. Проверяем именно наличие текста заголовка (без учёта регистра).
"""
import helpers as h

c = h.Checks("pe_abbrev_ru")
pdf = h.compile("pe_abbrev_ru.typ")
norm = " ".join(h.text(pdf).split())

c.check("heading_text", "перечень сокращений и ссылок" in norm.lower(),
        f"нет заголовка 'Перечень сокращений и ссылок' в:\n{norm[:200]}")
c.done()
