"""pe_authors_ru: русский алиас #список_исполнителей даёт заголовок 'Список исполнителей'."""
import helpers as h

c = h.Checks("pe_authors_ru")
pdf = h.compile("pe_authors_ru.typ")
norm = " ".join(h.text(pdf).split())

# Структурный заголовок из белого списка → рендерится в верхнем регистре.
c.check("heading_upper", "СПИСОК ИСПОЛНИТЕЛЕЙ" in norm,
        f"нет 'СПИСОК ИСПОЛНИТЕЛЕЙ' в:\n{norm[:200]}")
# Регистронезависимая проверка исходного текста заголовка.
c.check("heading_ci", "список исполнителей" in norm.lower(),
        "нет заголовка 'Список исполнителей' (без учёта регистра)")
c.done()
