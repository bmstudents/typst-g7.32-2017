"""pe_unnumbered_ru: русский #ненумерованный_заголовок(содержание: [Имя])[Текст] компилируется;
текст заголовка появляется, а переданное имя попадает в оглавление."""
import helpers as h

c = h.Checks("pe_unnumbered_ru")
pdf = h.compile("pe_unnumbered_ru.typ")  # бросит при ошибке компиляции
norm = " ".join(h.text(pdf).split())

# Тело заголовка рендерится (структурный путь L1 капсует ненумерованные).
c.check("body_text", "ТЕКСТ НЕНУМЕРОВАННОГО РАЗДЕЛА" in norm,
        f"нет текста ненумерованного заголовка в:\n{norm[:200]}")
# Имя для оглавления (аргумент содержание:) попадает в outline.
c.check("toc_name", "ИмяВОглавлении" in norm,
        "имя из аргумента 'содержание:' не появилось в оглавлении")
c.done()
