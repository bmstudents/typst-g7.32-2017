"""pg_fig_rotated: #рис(..., повернуто: true)[Альбомная] компилируется и даёт «Рисунок 1» в тексте.

Параметр называется «повернуто» (БЕЗ ё). Тело поворачивается на 90°,
подпись «Рисунок N» остаётся читаемой горизонтально в текстовом слое.
"""
import helpers as h

c = h.Checks("pg_fig_rotated")
pdf = h.compile("pg_fig_rotated.typ")  # сам факт компиляции — часть проверки
t = h.text(pdf)

# Компилируется в непустой PDF.
c.check("compiles", h.page_count(pdf) >= 1, "нет страниц в результате")

# Номер рисунка в тексте.
c.check("supplement", "Рисунок 1" in t, f"нет «Рисунок 1» в:\n{t}")

# Подпись повёрнутого рисунка читается горизонтально целиком.
c.check("caption_horizontal", "Рисунок 1 — Альбомная" in t,
        f"подпись повёрнутого рисунка не найдена в:\n{t}")

c.done()
