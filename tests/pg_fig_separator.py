"""pg_fig_separator: подпись содержит разделитель « — » между номером и названием: «Рисунок 1 — Структурная схема»."""
import helpers as h

c = h.Checks("pg_fig_separator")
pdf = h.compile("pg_fig_separator.typ")
t = h.text(pdf)

# Полная подпись с тире-разделителем (из separator: [ -- ] после типографики).
c.check("full_caption", "Рисунок 1 — Структурная схема" in t,
        f"подпись с разделителем « — » не найдена в:\n{t}")

# Тире-разделитель присутствует именно между номером и названием.
c.check("dash_separator", "1 — Структурная" in t,
        f"разделитель « — » между номером и названием не найден в:\n{t}")

# Это en-dash, не точка («Рисунок 1. Название» — неверно для ГОСТ).
c.check("not_dot", "Рисунок 1." not in t,
        f"встречена точка после номера вместо тире:\n{t}")

c.done()
