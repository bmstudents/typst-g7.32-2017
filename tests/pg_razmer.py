"""pg_razmer: размер(n) возвращает положительную длину (14pt*n - 3pt), пригодную как высота rect.

размер(5)=67pt, размер(3)=39pt — обе положительны. Проверяем:
1. компиляция .typ, где размер() используется и как печатное значение, и как высота rect;
2. печатное значение размер(5) == «67pt» (положительная длина);
3. rect высотой размер(5) выше rect высотой размер(3) (вертикальный зазор больше).
"""
import helpers as h

c = h.Checks("pg_razmer")
pdf = h.compile("pg_razmer.typ")  # компиляция = первая проверка
t = h.text(pdf)
W = h.words(pdf)

# Печатное значение размер(5) = 14*5-3 = 67pt, и это положительная длина.
c.check("value_67pt", "67pt" in t, f"ожидали «67pt» (размер(5)) в тексте:\n{t!r}")

# Слово-метка высокого и низкого блоков присутствуют.
hi = next((w for w in W if w[5] == "Высокий"), None)
lo = next((w for w in W if w[5] == "Низкий"), None)
c.check("blocks_present", hi is not None and lo is not None,
        f"метки блоков не найдены: Высокий={hi is not None} Низкий={lo is not None}")

# rect высотой размер(5)=67pt выше rect высотой размер(3)=39pt:
# зазор по Y между метками двух блоков > 60pt (≈ высота верхнего блока).
if hi is not None and lo is not None:
    gap = lo[2] - hi[2]
    c.check("taller_box_bigger_gap", gap > 60,
            f"зазор между блоками {gap:.1f}pt мал — высота размер(5) не положительна/не применилась")

c.done()
