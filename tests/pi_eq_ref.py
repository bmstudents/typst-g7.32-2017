"""pi п.12 eq-ref: $x=1$ <e1>, ссылка @e1 в тексте раскрывается в '(1)'."""
import re
import helpers as h

c = h.Checks("pi_eq_ref")
pdf = h.compile("pi_eq_ref.typ")
t = h.text(pdf)

# Должны быть два вхождения '(1)': номер у формулы и раскрытая ссылка @e1.
count = t.count("(1)")
c.check("two_occurrences", count >= 2,
        f"ожидалось >=2 вхождений '(1)' (номер + ссылка), найдено {count}:\n{t[:400]}")

# Ссылка раскрылась именно в '(1)' рядом с текстом-маркером строки ссылки.
c.check("ref_resolved", re.search(r"ССЫЛКАМаркер\s*\(1\)", t) is not None,
        f"ссылка @e1 не раскрылась в '(1)' рядом с маркером:\n{t[:400]}")

# Ссылка не осталась нераскрытой (нет 'e1' и нет '@e1' и нет '???')
c.check("no_raw_label", "@e1" not in t and "???" not in t,
        f"ссылка осталась нераскрытой ('@e1'/'???') в:\n{t[:400]}")
c.done()
