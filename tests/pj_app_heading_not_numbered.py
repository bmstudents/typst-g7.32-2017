"""pj 12: заголовок приложения НЕ получает номер раздела ('1 ПРИЛОЖЕНИЕ' и т.п.).

Проверка позиционная: плоский текст склеивает футер стр.1 ('1') с заголовком
стр.2 ('ПРИЛОЖЕНИЕ А'), поэтому substring-проверка даёт ложный плюс. Смотрим
координаты: на странице титула приложения слева от 'ПРИЛОЖЕНИЕ' на той же
строке не должно быть числа-номера раздела.
"""
import helpers as h

c = h.Checks("pj_app_heading_not_numbered")
pdf = h.compile("pj_app_heading_not_numbered.typ")
t = " ".join(h.text(pdf).split())

c.check("appendix_present", "ПРИЛОЖЕНИЕ А" in t,
        f"нет 'ПРИЛОЖЕНИЕ А' в:\n{t[:400]}")

# Раздел основного документа всё ещё пронумерован (1 Первый раздел).
c.check("main_section_numbered", "1 Первый раздел" in t,
        f"основной раздел не пронумерован '1 Первый раздел':\n{t[:400]}")

# Заведомо «номерные» формы заголовка приложения недопустимы.
for bad in ("ПРИЛОЖЕНИЕ 1", "ПРИЛОЖЕНИЕ 2", "2 ПРИЛОЖЕНИЕ"):
    c.check(f"no_form[{bad}]", bad not in t,
            f"в заголовке приложения номер раздела: '{bad}' в:\n{t[:400]}")

# Позиционно: найти слово 'ПРИЛОЖЕНИЕ', и убедиться, что на той же строке
# (близкий y) слева от него нет числового токена (номера раздела).
ws = h.words(pdf)
appx = [w for w in ws if w[5] == "ПРИЛОЖЕНИЕ"]
c.check("found_heading_word", len(appx) >= 1, "не найдено слово 'ПРИЛОЖЕНИЕ'")
if appx:
    p, x0, y0, x1, y1, _ = appx[0]
    same_line_left = [
        w for w in ws
        if w[0] == p and abs(w[2] - y0) < 6 and w[3] <= x0 and w[5].rstrip(".").isdigit()
    ]
    c.check("no_number_left_of_title", len(same_line_left) == 0,
            f"слева от 'ПРИЛОЖЕНИЕ' на стр.{p} есть число-номер: {same_line_left}")
c.done()
