"""pj 9: собственная-нумерация:да -> футер внутри приложения малое число.

Документ имеет несколько страниц до приложения, поэтому глобальный номер
страницы там >= 4. При своей нумерации футер на странице контента приложения
должен показывать малое число (1), а не глобальное.
"""
import helpers as h

c = h.Checks("pj_app_own_numbering")
pdf = h.compile("pj_app_own_numbering.typ")
t = " ".join(h.text(pdf).split())

c.check("appendix_present", "ПРИЛОЖЕНИЕ А" in t,
        f"нет 'ПРИЛОЖЕНИЕ А' в:\n{t[:300]}")

n = h.page_count(pdf)
c.check("multi_page", n >= 4, f"ожидалось >=4 страниц, получено {n}")

# Последняя страница — страница контента приложения (после титула приложения).
# Её футер при своей нумерации должен быть маленьким числом (< номера страницы).
footer = h.footer_word(pdf, n)
c.check("own_footer_small",
        footer is not None and footer.isdigit() and int(footer) < n,
        f"футер последней стр.={footer!r}, ожидался малый номер (<{n}) при своей нумерации")
c.done()
