"""pk: одинаковый термин (один и тот же текст определения) дважды —
в разделе определение не дублируется N раз.

Реализация ведёт индексацию по ключу (lower(definition_text).trim): два
вхождения с одинаковым текстом получают index 0 и 1, но это ОДНО определение,
повторённое дважды. Корректное поведение — НЕ выводить дубликат в разделе.
Маркерное слово ИНТЕРФЕЙСДЕДУП встречается:
  - 2 раза в теле (два текста-ссылки? нет — ссылка "API"),
  - в разделе: ожидаем ровно 1 раз, если есть дедуп.
Так как текст-ссылки = "API" (а не текст определения), в теле слова
ИНТЕРФЕЙСДЕДУП нет вообще — оно появляется только в разделе.
"""
import helpers as h

c = h.Checks("pk_def_dedup")
pdf = h.compile("pk_def_dedup.typ")
norm = " ".join(h.text(pdf).split())

# Текст определения уникален и встречается только в разделе.
n = norm.count("ИНТЕРФЕЙСДЕДУП")
c.check("present_in_section", n >= 1,
        f"текст определения вообще не попал в раздел (count={n})")
c.check("not_duplicated", n == 1,
        f"БАГ ПАКЕТА: определение задублировано в разделе: count={n}, ожидалось 1. "
        f"definitions.typ: секция итерирует по ВСЕМ <internal-definition-entry> "
        f"без дедупа по ключу — одинаковый термин выводится N раз. "
        f"Текст:\n{norm[:600]}")
c.done()
