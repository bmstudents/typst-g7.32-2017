"""pk: после рендера раздела текст-ссылки из #определение остаётся на месте
в теле (превращается в кликабельную ссылку, но текстовый слой сохранён)."""
import helpers as h

c = h.Checks("pk_def_link_resolves")
pdf = h.compile("pk_def_link_resolves.typ")
norm = " ".join(h.text(pdf).split())

# Текст-ссылки виден в теле документа (а не схлопнулся при создании ссылки).
c.check("ref_text_in_body", "МАРКЕРССЫЛКА" in norm,
        f"текст-ссылки пропал из тела:\n{norm[:400]}")

# Сам термин-определение присутствует в разделе (цель ссылки отрендерена).
c.check("target_in_section",
        "текст со ссылками на другие документы" in norm,
        f"цель ссылки (определение) не отрендерена:\n{norm[:400]}")

# Текст-ссылки встроен в окружение тела.
c.check("inline_context", "упоминается МАРКЕРССЫЛКА как термин" in norm,
        "текст-ссылки не на своём месте в абзаце")
c.done()
