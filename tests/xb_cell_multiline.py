"""xb_cell_multiline: ячейка таблицы с длинным текстом в узкой колонке
columns:(4cm,1fr). Текст правой ячейки переносится на несколько строк
(уникальных yMin у слов этой ячейки >=3 — ячейка выросла по высоте), все
строки этой ячейки лежат правее левой колонки (x-старт примерно одинаков),
и текст не вылезает за правое поле."""
import helpers as h

c = h.Checks("xb_cell_multiline")
pdf = h.compile("xb_cell_multiline.typ")
ws = h.words(pdf)

# Левая ячейка "Параметр" задаёт границу колонок.
left = [w for w in ws if w[5] == "Параметр"]
assert left, "нет левой ячейки 'Параметр'"
left_x0, left_page = left[0][1], left[0][0]

# Слова правой ячейки: на той же странице, левее правого поля, и их x-старт
# заметно правее левой ячейки (правая колонка). Берём только слова тела
# таблицы (ниже подписи) — подпись содержит "Описание"? Нет, в подписи
# "Узкая колонка...". Слово "Описание" — первое слово правой ячейки.
# Идентифицируем правую ячейку по словам из её содержимого.
cell_marker = [w for w in ws if w[5] == "Описание" and w[0] == left_page]
assert cell_marker, "нет содержимого правой ячейки ('Описание')"
cell_y0 = cell_marker[0][2]
cell_x0 = cell_marker[0][1]

# Все слова правой ячейки: на странице, на y >= cell_y0, x0 >= (cell_x0 - 5)
# (выровнены по левому краю правой колонки), не футер.
right_cell = [w for w in ws
              if w[0] == left_page and w[2] >= cell_y0 - 2
              and w[1] >= left_x0 + 30 and w[2] < 700]
uniq_y = sorted({round(w[2], 1) for w in right_cell})

# 1. Текст ячейки переносится на 3+ строки (ячейка выросла по высоте).
c.check("cell_3plus_lines", len(uniq_y) >= 3,
        f"текст в ячейке не на 3+ строки: уникальных yMin={len(uniq_y)} "
        f"({uniq_y})")

# 2. Текст ячейки лежит в правой колонке: первое слово правой ячейки правее
#    левой ячейки.
c.check("cell_in_right_column", cell_x0 > left_x0 + 30,
        f"правая ячейка не в правой колонке: x0={round(cell_x0,1)} "
        f"vs левая x0={round(left_x0,1)}")

# 3. Перенос внутри ячейки не вылезает за правое поле (xMax <= 553).
max_x = max(w[3] for w in right_cell)
c.check("cell_within_right_margin", max_x <= 553,
        f"текст ячейки вылез за правое поле: xMax={round(max_x,1)} (> 553)")

c.done()
