"""xb_long_word: очень длинное слово (~42 буквы) в обычном абзаце.
Ожидание: слово переносится/умещается и НЕ вылезает за правое поле
(правый край текстовой области A4 при поле 15мм = 552.76pt; допуск до ~553).

НАЙДЕННЫЙ БАГ: при переносе длинного слова мягкий перенос (U+00AD)
рендерится ЗА правым полем — фрагмент 'электрокардиографияжелудочкового­'
имеет xMax=555.32, тогда как правая граница набора 552.76. Перенос
свисает за поле на ~2.5pt. Для сравнения, обычное слово 'специалистов'
на соседней justify-строке заканчивается ровно на 552.76.
Источник: styles/page.typ — set text(costs:(hyphenation:1000%),
hyphenate:feature-text-hyphenate); дефис переноса не подтягивается внутрь
поля (нет hanging-punctuation/защиты правого края для дефиса переноса)."""
import helpers as h

c = h.Checks("xb_long_word")
pdf = h.compile("xb_long_word.typ")
ws = h.words(pdf)
t = h.text(pdf)

LONG = "электрокардиографияжелудочковоготрепетания"

# Слова абзаца (без футера: y < 700).
body = [w for w in ws if w[2] < 700]
SOFT = chr(0x00AD)

# 1. Длинное слово реально присутствует (целиком или как фрагменты переноса).
joined = t.replace(SOFT, "").replace("\n", "")
c.check("long_word_present", LONG in joined,
        f"длинного слова нет в тексте (даже после склейки переносов):\n{t!r}")

# 2. Никакое слово/фрагмент абзаца не выходит за правое поле (xMax <= 553).
overflow = [(round(w[3], 2), w[5]) for w in body if w[3] > 553]
c.check("no_right_margin_overflow", not overflow,
        f"за правое поле (xMax>553, граница набора 552.76) вылезли: {overflow}")

# 3. Конкретно фрагмент переноса длинного слова не свисает за поле.
frag = [w for w in body if w[5].startswith("электрокардиограф")]
frag_max = max((w[3] for w in frag), default=0)
c.check("hyphen_fragment_within_margin", frag and frag_max <= 553,
        f"фрагмент длинного слова заканчивается на xMax={round(frag_max,2)} "
        f"(> 553); дефис переноса свисает за правое поле 552.76")

c.done()
